// ---------------------------------------------------------------------
// 1. サーバー情報の多次元配列を作る
// ---------------------------------------------------------------------
// PHPの配列には大きく2種類あります。
//   ・添字配列(インデックス配列): キーが 0, 1, 2, ... のように自動で振られる配列
//     例: ["web01", "web02", "web03"]
//   ・連想配列: キーに自分で名前(文字列や数値)を付けられる配列
//     例: ["name" => "web01", "cpu" => 85]
//
// ここでは、1台のサーバー情報を「連想配列」として表現し、
// それをさらに「添字配列」の中に複数並べています。
// このように配列の中に配列が入っている状態を「多次元配列」と呼びます。
//
// 連想配列を使うことで、"$server[0]" のように「何番目の値か」ではなく、
// "$server['cpu']" のように「何の値か」がひと目でわかるようになります。
$servers = [
    ["name" => "web01",   "cpu" => 85, "memory" => 60],
    ["name" => "web02",   "cpu" => 45, "memory" => 70],
    ["name" => "db01",    "cpu" => 92, "memory" => 88],
    ["name" => "app01",   "cpu" => 30, "memory" => 55],
    ["name" => "cache01", "cpu" => 78, "memory" => 40],
];

echo "----- 1. 元のサーバー一覧(登録順) -----" . PHP_EOL;
// $servers は「添字配列(外側)の中に連想配列(内側)が入った多次元配列」なので、
// foreach で1台ずつ取り出し、さらに ['name'] のようにキーを指定して
// 内側の連想配列から値を取り出します。
foreach ($servers as $server) {
    echo "{$server['name']}: CPU {$server['cpu']}% / メモリ {$server['memory']}%" . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 2. CPU使用率が高い順に並び替える
// ---------------------------------------------------------------------
// usort() は「値」で配列を並び替える関数で、キーは振り直され、
// 自分で決めたルール(比較関数)で並び順を決められるのが特徴です。
//
// 比較関数(usortの第2引数)は、2つの要素 $a と $b を受け取り、
//   ・$a を先にしたい  -> 負の数を返す
//   ・$b を先にしたい  -> 正の数を返す
//   ・どちらでもよい   -> 0 を返す
// というルールで結果(負・正・0)を返す必要があります。
//
// 今回は「CPU使用率が高い順(降順)」にしたいので、
// $b の cpu から $a の cpu を引いた値を返します。
// こうすると、$b のほうがCPU使用率が高いときに正の数になり、
// 「$aより$bを先にする」という判定になるため、結果的に降順(高い順)になります。
usort($servers, function ($a, $b) {
    return $b["cpu"] - $a["cpu"];
});

echo "----- 2. CPU使用率が高い順に並び替え -----" . PHP_EOL;
foreach ($servers as $server) {
    echo "{$server['name']}: CPU {$server['cpu']}%" . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 3. CPU使用率が80%以上のサーバーだけを抽出する
// ---------------------------------------------------------------------
// array_filter() は「配列の中から、条件に合う要素だけを残す」関数です。
// 第2引数に渡したコールバック関数が true を返した要素だけが、
// 新しい配列にそのまま残ります(元の $servers は変更されません)。
//
// ここでは「cpuが80以上かどうか」を判定するコールバックを渡しています。
$highCpuServers = array_filter($servers, function ($server) {
    return $server["cpu"] >= 80;
});

// 注意: array_filter() は要素を取り除いたあとも、
//       元の配列のキー(添字)をそのまま引き継ぎます。
//       そのため、間の要素が抜けて「0, 2, 4」のように
//       キーが飛び飛びになることがあります。
//       連番のキーに振り直したい場合は array_values() を使います。
$highCpuServers = array_values($highCpuServers);

echo "----- 3. CPU使用率が80%以上のサーバー -----" . PHP_EOL;
foreach ($highCpuServers as $server) {
    echo "{$server['name']}: CPU {$server['cpu']}%" . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 4. 表示用の文字列一覧を作る
// ---------------------------------------------------------------------
// array_map() は「配列の全要素を1つずつ変換して、新しい配列を作る」関数です。
// array_filter() が「要素を減らす」のに対して、array_map() は
// 「要素の数は変えずに、中身だけを変換する」という違いがあります。
//
// ここでは、各サーバーの連想配列を "web01: CPU 85%" のような
// 表示用の文字列に変換しています。
// (並び替え後の $servers を使っているので、CPU使用率が高い順の文字列一覧になります)
$displayLines = array_map(function ($server) {
    return "{$server['name']}: CPU {$server['cpu']}%";
}, $servers);

echo "----- 4. 表示用の文字列一覧 -----" . PHP_EOL;
foreach ($displayLines as $line) {
    echo $line . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 5. 平均CPU使用率を計算する
// ---------------------------------------------------------------------
// array_reduce() は「配列の全要素を、順番に処理しながら1つの値にまとめる」関数です。
// array_map() が「要素の数だけ結果を作る」のに対して、array_reduce() は
// 「最終的に1つの結果だけを作る」という違いがあります(合計・平均・最大値などの計算に向いています)。
//
// コールバック関数は次の2つの引数を受け取ります。
//   $carry  : これまでの計算結果(1つ前の呼び出しの戻り値)
//   $server : 今回処理する要素
// そして「新しい $carry の値」を返します。
//
// array_reduce() の第3引数(0)は「初期値」です。
// 初期値を指定しておくことで、最初の要素を処理するときの $carry が
// 0からスタートするようになります。配列が空のときに備える意味でも重要です。
$totalCpu = array_reduce($servers, function ($carry, $server) {
    return $carry + $server["cpu"];
}, 0);

// 合計を求めたら、サーバーの台数(count()で取得)で割って平均を計算します。
// round() で小数点以下1桁に丸めて、見やすい表示にしています。
$averageCpu = round($totalCpu / count($servers), 1);

echo "----- 5. 平均CPU使用率 -----" . PHP_EOL;
echo "サーバー台数: " . count($servers) . "台" . PHP_EOL;
echo "CPU使用率の合計: {$totalCpu}" . PHP_EOL;
echo "平均CPU使用率: {$averageCpu}%" . PHP_EOL;
echo PHP_EOL;


// ---------------------------------------------------------------------
// (おまけ) サーバー名をアルファベット順に並び替える
// ---------------------------------------------------------------------
// asort() は「値」を基準に並び替えながら、キーと値の対応関係(紐付き)を
// そのまま保持してくれる関数です。
// (似た関数の sort() は、並び替えたあとにキーを 0, 1, 2... に振り直してしまいます)
//
// array_column() は、多次元配列から特定のキーの値だけを集めて
// 新しい配列を作る関数です。ここでは "name" の値だけを集めています。
$serverNames = array_column($servers, "name");

// asort() は引数で渡した配列そのものを並び替える(参照渡し)関数なので、
// 戻り値を受け取る必要はありません。
asort($serverNames);

echo "----- (おまけ) サーバー名のアルファベット順 -----" . PHP_EOL;
// asort() 後もキーは元のまま(振り直されない)なので、
// foreach で表示するときはキーを気にせず値だけを取り出せば十分です。
foreach ($serverNames as $name) {
    echo $name . PHP_EOL;
}
