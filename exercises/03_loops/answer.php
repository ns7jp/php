// ---------------------------------------------------------------------
// 0. 準備運動: for・while・do-whileの比較
// ---------------------------------------------------------------------
// 同じ「1から5まで数字を出力する」という処理を、3つの書き方で比較します。
// どれも最終的な結果(1 2 3 4 5)は同じですが、
// 「いつ条件をチェックするか」という点に違いがあります。
echo "----- 準備運動: for・while・do-whileの比較 -----" . PHP_EOL;

// [1] for文
// 「初期化; 条件; 更新」の3つを () の中にまとめて書けるのが特徴です。
// 「繰り返す回数があらかじめ決まっている」処理(今回のFizzBuzzのように
// 「1から100まで」と最初から範囲が決まっているもの)と特に相性が良い書き方です。
echo "[for文]      ";
for ($i = 1; $i <= 5; $i++) {
    echo $i . " ";
}
echo PHP_EOL;

// [2] while文
// () の中に条件だけを書き、初期化と更新は自分で外に書く必要があります。
// 「条件を満たしている間、繰り返す」という、より自由度の高い書き方です。
// 「何回繰り返すか事前にはわからないが、ある条件を満たすまで続けたい」
// という処理(今回のヘルスチェックのリトライ処理など)に向いています。
echo "[while文]    ";
$i = 1;
while ($i <= 5) {
    echo $i . " ";
    $i++; // 更新を忘れると無限ループになるので注意
}
echo PHP_EOL;

// [3] do-while文
// while文とほぼ同じですが、「条件チェックが最後に来る」という違いがあります。
// そのため、do-while文は条件の真偽にかかわらず、必ず最低1回は中身が実行されます。
echo "[do-while文] ";
$i = 1;
do {
    echo $i . " ";
    $i++;
} while ($i <= 5);
echo PHP_EOL;

// この違いを確認するために、「最初から条件を満たさない」ケースも試してみます。
echo "[while文]    条件が最初からfalseの場合 -> ";
$i = 10; // $i <= 5 は最初から false
while ($i <= 5) {
    // ここは一度も実行されない
    echo $i . " ";
    $i++;
}
echo "(何も表示されない = 1回も実行されない)" . PHP_EOL;

echo "[do-while文] 条件が最初からfalseの場合 -> ";
$i = 10; // $i <= 5 は最初から false
do {
    // while文と違い、条件を確認する前に必ず1回実行される
    echo $i . " ";
    $i++;
} while ($i <= 5);
echo "(条件はfalseでも1回だけ実行される)" . PHP_EOL;
echo PHP_EOL;


// ---------------------------------------------------------------------
// 1. FizzBuzz(for文)
// ---------------------------------------------------------------------
// FizzBuzzは「プログラミング初心者の練習問題」として非常によく使われる
// お題で、繰り返し処理と条件分岐を組み合わせる練習になります。
// 「1から100まで」という繰り返す回数があらかじめ決まっているので、
// for文を使うのが自然です。
echo "----- FizzBuzz (1〜100) -----" . PHP_EOL;

for ($number = 1; $number <= 100; $number++) {
    // 剰余演算子 "%" は割り算の余りを求める演算子です。
    // "$number % 3 === 0" は「$numberを3で割った余りが0」、
    // つまり「$numberが3の倍数である」ことを意味します。
    //
    // 注意点: 「3の倍数かどうか」と「5の倍数かどうか」を別々に判定する前に、
    // 「15の倍数(3の倍数かつ5の倍数)かどうか」を先にチェックする必要があります。
    // もし先に「3の倍数か」だけをチェックしてしまうと、
    // 15は3の倍数でもあるため、"FizzBuzz"ではなく"Fizz"と判定されてしまいます。
    if ($number % 15 === 0) {
        // 15の倍数 = 3の倍数かつ5の倍数
        echo "FizzBuzz" . PHP_EOL;
    } elseif ($number % 3 === 0) {
        echo "Fizz" . PHP_EOL;
    } elseif ($number % 5 === 0) {
        echo "Buzz" . PHP_EOL;
    } else {
        // どの倍数でもない場合は、数字そのものを出力する
        echo $number . PHP_EOL;
    }
}

echo PHP_EOL;


// ---------------------------------------------------------------------
// 2. サーバー一覧からwebサーバーだけ接続確認(foreach + continue)
// ---------------------------------------------------------------------
// サーバー名が入った配列を、foreachを使って1つずつ取り出して処理します。
// foreachは「配列の中身を先頭から順番に全部処理したい」ときに使う、
// 配列専用の繰り返し構文です。
$servers = ["web01", "web02", "db01", "cache01"];

echo "----- サーバー一覧からwebサーバーだけ接続確認 -----" . PHP_EOL;

foreach ($servers as $serverName) {
    // str_contains(対象の文字列, 探したい文字列) は、
    // 「対象の文字列の中に、探したい文字列が含まれているか」を
    // true/falseで返してくれる関数です(PHP8.0以降で使えます)。
    //
    // ここでは「"web"を含まない名前」を処理の対象外にしたいので、
    // 頭に "!" を付けて条件を反転させ、"含まない場合" にcontinueしています。
    if (!str_contains($serverName, "web")) {
        // continueは「今回のループの残りの処理だけ」をスキップし、
        // すぐに次のサーバー名の処理に進みます。
        // ループ自体は終わらない(breakとの違い)点に注意してください。
        continue;
    }

    echo "{$serverName} に接続確認中..." . PHP_EOL;
}

echo PHP_EOL;


// ---------------------------------------------------------------------
// 3. 二重ループで再現するヘルスチェックのリトライ処理
// ---------------------------------------------------------------------
// 実際のサーバー監視では、1回失敗しただけで即座に「異常」とはみなさず、
// 何回か再試行(リトライ)してから最終的な判定を行うことがよくあります。
//
// ここでは実際に通信は行わず、あらかじめ用意した true(成功)/false(失敗)の
// 固定データを使って、その様子を疑似的に再現します。
// キーがサーバー名、値が「5回分のチェック結果の配列」になっている、
// 「配列の中に配列が入った」データ構造です。
$healthCheckResults = [
    "web01" => [true,  true,  true,  true,  true],  // すべて成功
    "web02" => [true,  false, false, false, true],  // 2〜4回目が3回連続で失敗する
    "db01"  => [false, true,  false, true,  false], // 失敗はあるが連続しない
];

echo "----- ヘルスチェックのリトライ処理(3台 × 5回) -----" . PHP_EOL;

// 外側のループ: foreachで「サーバーごと」に処理を繰り返す。
// $serverName にはキー(サーバー名)、$results にはそのサーバーの
// 5回分のチェック結果の配列(true/falseの配列)が入ります。
foreach ($healthCheckResults as $serverName => $results) {
    echo "◆ {$serverName} のヘルスチェックを開始します" . PHP_EOL;

    // 「連続で何回失敗しているか」を数えるためのカウンター。
    // 成功するたびに0にリセットし、失敗するたびに+1していきます。
    $consecutiveFailures = 0;

    // 何回目のチェックかを表すカウンター(1回目、2回目、…と数えるために使う)
    $attempt = 0;

    // このサーバーの合計チェック回数(=$results配列の要素数、通常は5)
    $totalAttempts = count($results);

    // 内側のループ: while文で「1回目から5回目まで」の結果を順番に確認する。
    // 「あらかじめ決まった5回」を繰り返すだけならfor文でも書けますが、
    // ここでは「途中で条件(3回連続失敗)を満たしたら早めに終わる」ことを
    // 意識しやすいwhile文で書いています。
    while ($attempt < $totalAttempts) {
        $attempt++; // 1回目のチェックとして数える
        $isSuccess = $results[$attempt - 1]; // 配列の添字は0から始まるので-1する

        if ($isSuccess) {
            echo "  {$attempt}回目: 成功" . PHP_EOL;
            // 成功したら、連続失敗のカウントはリセットする
            // (例: 失敗→失敗→成功→失敗 の場合、最後の失敗は「連続1回目」として数え直す)
            $consecutiveFailures = 0;
        } else {
            $consecutiveFailures++;
            echo "  {$attempt}回目: 失敗(連続失敗{$consecutiveFailures}回目)" . PHP_EOL;

            if ($consecutiveFailures >= 3) {
                // 3回連続で失敗したので、このサーバーへの残りのチェックは
                // これ以上続けても無駄と判断し、内側のwhileループをbreakで打ち切る。
                //
                // 重要: このbreakが抜けるのは「内側のwhileループ」だけです。
                // 外側のforeachループ(サーバーの繰り返し)はそのまま続き、
                // 次のサーバー(この例ではdb01)のチェックに進みます。
                echo "  → 3回連続で失敗したため、このサーバーへのチェックを打ち切ります" . PHP_EOL;
                break;
            }
        }
    }

    echo PHP_EOL;
}

// 実行結果の見方:
//   web01: 5回とも成功するので、そのまま5回チェックが行われる
//   web02: 2〜4回目が3回連続で失敗するため、4回目の時点でbreakが実行され、
//          5回目のチェックは行われずに次のサーバー(db01)へ進む
//   db01 : 失敗はあるが3回連続にはならないため、最後まで5回チェックが行われる
