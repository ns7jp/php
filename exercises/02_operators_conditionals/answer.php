// ---------------------------------------------------------------------
// 1. ディスク空き容量の判定
// ---------------------------------------------------------------------
// サーバーの監視ツールなどでは、ディスクの空き容量が少なくなると
// アラート(警告)を出す仕組みが一般的です。
// ここでは「空き容量(%)」を1つの変数で表現し、
// if / elseif / else を使って3段階の状態に分類します。
$diskFreePercent = 15;

echo "----- ディスク空き容量の判定 -----" . PHP_EOL;
echo "空き容量: {$diskFreePercent}%" . PHP_EOL;

// 比較演算子 ">=" (以上) や "<" (未満) を使って、数値の範囲を判定します。
// 条件は「上から順番に」チェックされるため、
// 先に「90以上か」を確認し、そうでなければ次に「50以上か」を確認する、
// という流れになっています。
// このように上から順にチェックすることで、
// 「90以上」の条件と「50以上90未満」の条件が重ならないようにできます。
if ($diskFreePercent >= 90) {
    // 90%以上なら十分に空きがある状態
    $diskStatus = "正常";
} elseif ($diskFreePercent >= 50) {
    // ここに来る時点で90未満であることは確定しているので、
    // "50以上90未満" という条件を "50以上" だけで表現できる
    $diskStatus = "注意";
} else {
    // 90未満でも50以上でもない、つまり50未満
    $diskStatus = "危険";
}

echo "判定結果: {$diskStatus}" . PHP_EOL;
echo PHP_EOL;


// ---------------------------------------------------------------------
// 2. HTTPステータスコードの分類(switch文編)
// ---------------------------------------------------------------------
// Webサーバーが返すHTTPステータスコードを、人間が読みやすい文字列に変換します。
// 同じ値と何度も比較したい場合は、if/elseifを並べるより
// switch文を使った方が見通しがよくなることがあります。
$httpStatusCode = 404;

echo "----- HTTPステータスコードの分類(switch文) -----" . PHP_EOL;
echo "ステータスコード: {$httpStatusCode}" . PHP_EOL;

// switch文は、() の中の値([$httpStatusCode])と一致する case を探して
// そこから処理を実行します。
// 注意点: case の処理の最後に break を書かないと、
//         一致した case より後ろの処理までそのまま実行されてしまいます
//         (これを「フォールスルー」と呼びます)。
//         そのため、各 case の最後には必ず break を書きます。
switch ($httpStatusCode) {
    case 200:
        $statusMessageBySwitch = "OK";
        break;
    case 301:
        $statusMessageBySwitch = "リダイレクト";
        break;
    case 404:
        $statusMessageBySwitch = "Not Found";
        break;
    case 500:
        $statusMessageBySwitch = "サーバーエラー";
        break;
    default:
        // どの case にも一致しなかった場合はここに来る
        $statusMessageBySwitch = "不明なステータス";
        break;
}

echo "switchでの判定結果: {$statusMessageBySwitch}" . PHP_EOL;
echo PHP_EOL;


// ---------------------------------------------------------------------
// 3. HTTPステータスコードの分類(match式編)
// ---------------------------------------------------------------------
// match式はPHP8から追加された比較的新しい構文です。
// switch文と同じような「値による分岐」を、より短く安全に書けます。
//
// switch文との主な違い:
//   ・比較は常に "===" (型まで含めた厳密比較)で行われる
//   ・case ごとに break を書く必要がない(フォールスルーが起きない)
//   ・match は「式」なので、結果をそのまま変数に代入できる
echo "----- HTTPステータスコードの分類(match式) -----" . PHP_EOL;
echo "ステータスコード: {$httpStatusCode}" . PHP_EOL;

$statusMessageByMatch = match ($httpStatusCode) {
    200 => "OK",
    301 => "リダイレクト",
    404 => "Not Found",
    500 => "サーバーエラー",
    // switch文のdefaultにあたるものが、matchでは default
    default => "不明なステータス",
};

echo "matchでの判定結果: {$statusMessageByMatch}" . PHP_EOL;
echo PHP_EOL;

// switchとmatchで同じロジックを書いたので、
// 同じ $httpStatusCode を渡せば結果は必ず一致するはずです。
// ここでは "===" を使って、値だけでなく型まで一致しているかを確認しています。
if ($statusMessageBySwitch === $statusMessageByMatch) {
    echo "switchとmatchの結果は一致しています。" . PHP_EOL;
} else {
    echo "switchとmatchの結果が一致していません。実装を見直してみましょう。" . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 4. null合体演算子(??)の練習
// ---------------------------------------------------------------------
// 設定ファイルや設定用の配列では、
// 「値が設定されている場合はその値を使い、設定されていない場合はデフォルト値を使う」
// という処理が非常によく出てきます。
//
// $config["timeout"] のように配列の存在しないキーへアクセスすると、
// 通常はエラー(正確には警告)が出てしまいます。
// これを防ぐために isset() を使って
//     $timeoutSeconds = isset($config["timeout"]) ? $config["timeout"] : 30;
// のように書くこともできますが、null合体演算子 "??" を使うと
// 同じ処理をもっと短く安全に書くことができます。
$config = [
    "host" => "example.com",
    // "timeout" キーはわざと設定していません(未設定の状態を再現するため)
];

echo "----- null合体演算子(??)の練習 -----" . PHP_EOL;

// "$config["timeout"] ?? 30" は、
//   ・$config["timeout"] が存在し、かつ null でなければ その値を使う
//   ・存在しない、または null であれば 30 を使う
// という意味になります。
$timeoutSeconds = $config["timeout"] ?? 30;

echo "タイムアウト秒数: {$timeoutSeconds}" . PHP_EOL;

// おまけ: 三項演算子との比較
// 三項演算子「条件 ? 真の場合 : 偽の場合」を使うと、
// 短いif/elseを1行で書くことができます。
// 例えば「タイムアウトが60秒より長いかどうか」を判定する場合はこう書けます。
$timeoutLabel = $timeoutSeconds > 60 ? "長め" : "標準的";
echo "タイムアウトの長さ: {$timeoutLabel}" . PHP_EOL;
