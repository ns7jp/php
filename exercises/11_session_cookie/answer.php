<?php

// =====================================================================
// 演習11: セッション・Cookie管理
// =====================================================================
// このファイルは模範解答です。
// - session_start() と $_SESSION を使った「ログイン状態の保持」
// - setcookie() を使った、ブラウザ側への小さな情報の保存
// - session_destroy() を使った「ログアウト」処理
// を、実際に動くコードで確認しながら、
// 「ログイン → ログイン確認 → ログアウト」という一連の流れを
// 1つのファイルの中でシミュレートしていきます。
//
// 本来これらはWebブラウザからのアクセスがあって初めて意味を持つ
// 仕組みですが、この演習ではWebサーバーを使わずCLI(コマンドライン)
// だけで動作確認できるように、$_POST の値をあらかじめ配列として
// 用意するなどの工夫をしています。
// =====================================================================


// ---------------------------------------------------------------------
// 0. session_start() と setcookie() は、必ず「他の出力より前」に呼ぶ
// ---------------------------------------------------------------------
// session_start() や setcookie() は、内部的には「ブラウザに送り返す
// レスポンスヘッダー」を組み立てる処理を行っています。
// PHPは一度でも echo などで画面に文字を出力すると、その時点で
// 「ヘッダー部分の送信」を済ませてしまったものとして扱うため、
// それより後に session_start() や setcookie() を呼び出そうとすると
// 「Cannot modify header information - headers already sent」という
// 警告が出てしまいます。
// そのため、この2つの関数は必ずファイルの一番最初、他のechoなどの
// 出力処理より前にまとめて呼び出すようにします。

// session_start() を呼ぶと、
//   1. まだセッションが始まっていなければ、新しいセッションID
//      (このブラウザ・利用者を区別するための、ランダムな文字列)を発行する
//   2. サーバー側の保存領域(通常はファイル)から、そのセッションIDに
//      対応するデータを読み込んで $_SESSION に復元する
// という2つのことを行い、以降 $_SESSION という特別な配列(スーパー
// グローバル変数)を使って、ログイン状態などの情報を読み書きできる
// ようにしてくれます。
session_start();

// 「最終アクセス日時」を記録するCookieを1つ設定しておきます。
// setcookie(名前, 値, 有効期限のUNIXタイムスタンプ) という形で
// 指定します。ここでは「今から30日後まで有効」という意味で
// time() + 60 * 60 * 24 * 30 (30日分の秒数)を指定しています。
$lastAccessAt = date('Y-m-d H:i:s');
$cookieResult = setcookie('last_access', $lastAccessAt, time() + 60 * 60 * 24 * 30);


// ---------------------------------------------------------------------
// 関数の定義: checkLoginStatus()
// ---------------------------------------------------------------------
/**
 * $_SESSION の内容を確認し、ログイン状態を表す文字列を返す。
 *
 * ログイン処理を行った画面と、ログイン確認を行う画面(マイページなど)
 * は、実際のWebアプリケーションでは別のファイル・別のリクエストに
 * なっていることがほとんどです。しかし「$_SESSION を読み取って
 * 状態を判定する」というやり方はどちらも同じなので、この演習では
 * 関数としてひとまとめにし、ログアウト前後の2箇所から呼び出して
 * 使い回します。
 *
 * @return string ログイン状態を表すメッセージ
 */
function checkLoginStatus(): string
{
    // isset() を使うことで、'logged_in' というキーがそもそも
    // 存在しない場合(まだログインしていない場合や、
    // ログアウト後で $_SESSION が空になっている場合)でも、
    // 警告を出さずに安全にチェックできます。
    // 値の比較には === を使い、"true っぽい何か" ではなく、
    // 真偽値としての true そのものが入っているかを厳密に確認します。
    if (isset($_SESSION['logged_in']) && $_SESSION['logged_in'] === true) {
        // $_SESSION の中身は、本来ユーザー自身が入力した値
        // (あるいはそれに由来する値)である可能性があるため、
        // 画面に表示する前には htmlspecialchars() を通す習慣を
        // 付けておきましょう(演習10で学んだXSS対策と同じ考え方です)。
        $userName = htmlspecialchars($_SESSION['user'], ENT_QUOTES, 'UTF-8');
        return "ログイン中のユーザー: {$userName}";
    }

    return 'ログインしていません';
}


// ---------------------------------------------------------------------
// 1. ログインフォームの入力をシミュレートする
// ---------------------------------------------------------------------
// 本来はHTMLの <form method="post"> から送信されてくる値ですが、
// この演習ではCLIで試せるように、$_POST に直接配列を代入して
// シミュレートします。
$_POST = [
    'id'       => 'admin',
    'password' => 'password123',
];

// サーバー側であらかじめ決めておいた「正しいID・パスワード」です。
// 本来はデータベースに保存されたユーザー情報と照合しますが、
// この演習ではシンプルに、固定値との比較で簡易的なログイン処理を
// 再現します。
//
// なお、実際のシステムでは、パスワードを平文(そのままの文字列)で
// 保存・比較することはありません。password_hash() で暗号学的に
// 安全な形に変換して保存し、ログイン時には password_verify() で
// 照合するのが正しいやり方です。この演習では仕組みの理解を
// 優先するため、あえて単純な文字列比較にしています。
$correctId = 'admin';
$correctPassword = 'password123';


// ---------------------------------------------------------------------
// 2. ログイン処理
// ---------------------------------------------------------------------
echo '===== 1. ログイン処理 =====' . PHP_EOL;

// 送信されたIDとパスワードが、あらかじめ決めた正しい値と一致するかを
// 比較します。=== (型と値が両方一致するかを見る、厳密な比較演算子)を
// 使うことで、意図しない型変換によって誤って一致してしまうことを
// 防ぎます。
if ($_POST['id'] === $correctId && $_POST['password'] === $correctPassword) {
    // ログインに成功したら、$_SESSION に「ログイン済みであること」と
    // 「誰としてログインしているか」を保存します。
    // $_SESSION に保存した内容は、(Webブラウザ経由でアクセスする
    // 場合)同じセッションIDを持つ次のリクエストでも引き継がれるため、
    // 「ページを移動してもログイン状態が保たれる」という
    // お馴染みの動きを実現できます。
    $_SESSION['logged_in'] = true;
    $_SESSION['user'] = $_POST['id'];

    echo 'ログインに成功しました' . PHP_EOL;
    echo '発行されたセッションID: ' . session_id() . PHP_EOL;
} else {
    echo 'IDまたはパスワードが正しくありません' . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 3. Cookie(最終アクセス日時)の確認
// ---------------------------------------------------------------------
echo '===== 2. Cookie(最終アクセス日時)の確認 =====' . PHP_EOL;

if ($cookieResult) {
    echo "'last_access' という名前のCookieに \"{$lastAccessAt}\" を設定しました。" . PHP_EOL;
} else {
    echo 'Cookieの設定に失敗しました。' . PHP_EOL;
}

// 【CLI実行時ならではの注意点】
// setcookie() は、「次にこのサイトへアクセスしてきたときに、
// この値を一緒に送り返してください」とブラウザに指示するための
// 関数です。Webブラウザで動いている場合は、この指示が
// Set-Cookieレスポンスヘッダーとしてブラウザに届き、
// 次のページを読み込むタイミングから $_COOKIE['last_access'] に
// この値が自動的に入るようになります。
// しかし、このスクリプトはWebブラウザを経由せずCLIで直接
// 実行しているため、「ブラウザが値を保存して、次のリクエストで
// 送り返してくる」という一連の流れそのものが発生しません。
// そのため、setcookie() を呼び出した直後、この同じスクリプトの
// 中で $_COOKIE['last_access'] を読み取っても、まだ値は
// 入っていません。実際に確認してみましょう。
if (isset($_COOKIE['last_access'])) {
    echo '$_COOKIE から読み取った値: ' . $_COOKIE['last_access'] . PHP_EOL;
} else {
    echo '$_COOKIE にはまだ値が入っていません' . PHP_EOL;
    echo '(CLIでは「ブラウザが保存して送り返す」という次のリクエストが発生しないためです。詳しくは explanation.md を参照してください)' . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 4. ログイン確認処理
// ---------------------------------------------------------------------
// 実際のWebアプリケーションでは、ログイン処理を行った画面とは別の
// 画面(マイページや管理画面のトップなど)で、
// 「今、誰がログインしているか」を $_SESSION から読み取って
// 表示する、という場面がよくあります。ここではその処理を
// checkLoginStatus() 関数として再現します。
echo '===== 3. ログイン確認処理 =====' . PHP_EOL;
echo checkLoginStatus() . PHP_EOL;
echo PHP_EOL;


// ---------------------------------------------------------------------
// 5. ログアウト処理
// ---------------------------------------------------------------------
echo '===== 4. ログアウト処理 =====' . PHP_EOL;

// session_destroy() は、サーバー側に保存されているセッションの
// データそのもの(セッションファイルなど)を破棄する関数です。
// これにより、以後同じセッションIDでアクセスしてきても、
// 保存されていたログイン情報などは失われます。
//
// ただし1点注意が必要です。session_destroy() を呼んだだけでは、
// 「現在実行中のこのスクリプトの中」にある $_SESSION 配列の中身は
// 自動的には空になりません(サーバー側の保存データが消えるだけで、
// メモリ上に読み込み済みの $_SESSION はそのまま残ります)。
// そのため、「見た目のうえでもログアウトした状態」を正しく再現する
// ためには、続けて $_SESSION = []; として配列自体も空にしておく
// 必要があります。
session_destroy();
$_SESSION = [];

echo 'session_destroy() を実行しました(サーバー側のセッションデータを破棄しました)' . PHP_EOL;
echo PHP_EOL;


// ---------------------------------------------------------------------
// 6. ログアウト後に、もう一度ログイン確認処理を行ってみる
// ---------------------------------------------------------------------
// 先ほどと同じ checkLoginStatus() をもう一度呼び出してみます。
// ログアウト処理が正しく行われていれば、今度は
// 「ログインしていません」と表示されるはずです。
echo '===== 5. ログアウト後の確認 =====' . PHP_EOL;
echo checkLoginStatus() . PHP_EOL;
