<?php

// =====================================================================
// 演習12: PDOとデータベース連携
// =====================================================================
// このファイルは模範解答です。
// PDO(PHP Data Objects)という仕組みを使って、
//   - データベースへの接続
//   - テーブルの作成
//   - プリペアドステートメントを使った INSERT / SELECT / UPDATE / DELETE
// という、データベース操作の基本(CRUD操作)をひととおり体験します。
//
// 本来PDOは MySQL や PostgreSQL のような「サーバー型」のデータベースに
// 接続するために使うことが多いのですが、この演習では「MySQLサーバーを
// 別途用意しなくても、すぐに手元で試せる」ように、PDOのSQLiteドライバを
// 使います。SQLiteは、サーバーを起動する必要がなく、1つのファイルが
// そのままデータベースになる、とても手軽なデータベースです。
//
// 重要なのは、PDOを使う限り「SQLiteでもMySQLでも、書き方はほとんど
// 同じ」だということです。この演習の最後のコメントで、MySQLに接続する
// 場合にどこを変えればよいかを説明します。
// =====================================================================


// ---------------------------------------------------------------------
// 0. データベースファイルのパスを準備する
// ---------------------------------------------------------------------
// __DIR__ は「このファイルが置かれているディレクトリの絶対パス」を
// 返してくれる、PHPのマジック定数です。これを使ってパスを組み立てる
// ことで、どのディレクトリから php コマンドを実行しても、
// servers.db が同じ場所に作られるようにします。
$dbPath = __DIR__ . '/servers.db';

// 演習を何度実行しても同じ結果になるように、実行の最初に
// 前回のデータベースファイルが残っていれば削除しておきます。
// file_exists() でファイルの存在を確認してから unlink() で削除します。
// (存在しないファイルに unlink() すると警告が出てしまうため)
if (file_exists($dbPath)) {
    unlink($dbPath);
}


echo '===== 1. PDOでデータベースに接続する =====' . PHP_EOL;

// -----------------------------------------------------------------
// PDOのインスタンスを作る = データベースに接続する、という意味です。
// new PDO(DSN, ユーザー名, パスワード) という形で使います。
//
// DSN(データソース名)は「どの種類のデータベースに、どうやって
// 接続するか」を1つの文字列にまとめたものです。
//   "sqlite:" . __DIR__ . "/servers.db"
// は、「SQLiteドライバを使って、このパスのファイルをデータベースとして
// 開く(なければ新規作成する)」という意味になります。
//
// SQLiteはファイル1つがデータベースそのものなので、サーバーへの
// 接続情報(ホスト名やユーザー名、パスワード)は不要です。
// そのため、第2引数・第3引数(ユーザー名・パスワード)は省略しています。
// -----------------------------------------------------------------
try {
    $pdo = new PDO('sqlite:' . $dbPath);

    // PDO::setAttribute() で、PDOの動作モードを設定できます。
    // PDO::ATTR_ERRMODE に PDO::ERRMODE_EXCEPTION を設定しておくと、
    // SQL文が間違っていたり、データベース側でエラーが起きたときに、
    // 「戻り値が false になるだけ」ではなく「例外(PDOException)が
    // 投げられる」ようになります。
    // 例外が飛ぶようになると、try/catch でまとめてエラーを検知できる
    // ので、エラーの発生に気づかずに処理が進んでしまう事故を防げます。
    // データベースを扱うプログラムでは、ほぼ必須の設定だと考えてください。
    $pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);

    echo "データベースに接続しました: {$dbPath}" . PHP_EOL;
} catch (PDOException $e) {
    // 接続自体に失敗した場合は、これ以降の処理を続けても意味がないので
    // メッセージを表示してスクリプトを終了します。
    echo 'データベースへの接続に失敗しました: ' . $e->getMessage() . PHP_EOL;
    exit(1);
}
echo PHP_EOL;


echo '===== 2. テーブルを作成する (CREATE TABLE) =====' . PHP_EOL;

// -----------------------------------------------------------------
// exec() は、SELECT文のように「結果の行」を返さないSQL文
// (CREATE TABLE, INSERT, UPDATE, DELETE など)を実行するためのメソッド
// です。ここでは servers テーブルをまだ作成していない場合に備えて、
// CREATE TABLE 文を実行します。
//
// テーブルの列(カラム)は要件どおり、以下の4つです。
//   - id     : INTEGER PRIMARY KEY AUTOINCREMENT
//              (自動的に連番が振られる主キー。データを一意に識別するID)
//   - name   : TEXT (サーバー名)
//   - ip     : TEXT (IPアドレス)
//   - status : TEXT (稼働状況。running / stopped など)
//
// SQL文の中身自体はプログラムから受け取った値を含まない
// (固定の文字列である)ため、ここではプリペアドステートメントを
// 使わず、そのまま exec() で実行しています。
// -----------------------------------------------------------------
$pdo->exec(
    'CREATE TABLE servers (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT,
        ip TEXT,
        status TEXT
    )'
);
echo 'servers テーブルを作成しました。' . PHP_EOL;
echo PHP_EOL;


echo '===== 3. プリペアドステートメントでデータを登録する (INSERT) =====' . PHP_EOL;

// -----------------------------------------------------------------
// ここからが、この演習でいちばん大事な「プリペアドステートメント」の
// 使い方です。
//
// もし SQL 文の中に、ユーザーが入力した値やプログラムの変数を
// 「文字列連結」でそのまま埋め込んでしまうと、SQLインジェクションと
// 呼ばれる重大なセキュリティ上の脆弱性につながります。
//
// ---- 悪い例(絶対に真似しないでください。実行はしません) ----
// $name = $_POST['name']; // 例えば外部から渡された値だとします
// $sql = "INSERT INTO servers (name, ip, status) VALUES ('" . $name . "', '192.168.1.1', 'running')";
// $pdo->exec($sql);
//
// もし $name に、悪意のある利用者が
//   例) hacked', '0.0.0.0', 'running'); DROP TABLE servers; --
// のような文字列を入力すると、文字列連結によって組み立てられる
// SQL文の「構造」そのものが書き換えられてしまいます。
// 上の例では、本来1件だけ登録するつもりが、
// テーブルを丸ごと削除する DROP TABLE 文まで実行されてしまう
// 危険性があります。これが「SQLインジェクション」です。
// 文字列連結でSQLを組み立てる限り、どんなに入力チェックを
// 頑張っても、あらゆる攻撃パターンを完全に防ぐのはとても困難です。
// --------------------------------------------------------------
//
// これを安全に行う方法が「プリペアドステートメント」です。
// 1. まず prepare() で、値の部分を "?"(プレースホルダー)にした
//    SQL文のひな形を用意します。この時点ではまだ実行されません。
// 2. 次に execute([値1, 値2, 値3]) で、プレースホルダーに
//    実際の値をあてはめて実行します。
//
// プリペアドステートメントでは、SQL文の「構造」と「値」が
// はっきり分離されているため、値の中にどんな文字列(たとえ
// SQLのキーワードのようなものであっても)が入っていても、
// それは単なる「データ」としてしか扱われません。
// そのため、値によってSQL文の構造が書き換えられることがなく、
// SQLインジェクションを防ぐことができます。
// -----------------------------------------------------------------

// INSERT用のSQL文のひな形を、prepare() で準備します。
// "?" の部分に、あとから execute() で値をあてはめます。
$insertStatement = $pdo->prepare(
    'INSERT INTO servers (name, ip, status) VALUES (?, ?, ?)'
);

// 登録したいサーバーの一覧を配列で用意しておきます。
$newServers = [
    ['web-01', '192.168.1.11', 'running'],
    ['web-02', '192.168.1.12', 'running'],
    ['db-01', '192.168.1.21', 'stopped'],
];

// 用意した prepare() 済みの文を、execute() で1件ずつ実行します。
// execute() に渡す配列の値が、SQL文中の "?" に順番にあてはめられます。
foreach ($newServers as $server) {
    $insertStatement->execute($server);
    echo "登録しました: {$server[0]} / {$server[1]} / {$server[2]}" . PHP_EOL;
}
echo PHP_EOL;


echo '===== 4. 全件をSELECTして一覧表示する =====' . PHP_EOL;

// -----------------------------------------------------------------
// SELECT文には値を埋め込む部分がないので、query() を使って直接
// 実行することもできますが、ここでも prepare() + execute() の
// 流れに統一しておくと、「値を条件に含むSELECT」に変更したくなった
// ときにも同じ書き方のまま対応できます。
// -----------------------------------------------------------------
$selectStatement = $pdo->prepare('SELECT id, name, ip, status FROM servers');
$selectStatement->execute();

// fetchAll(PDO::FETCH_ASSOC) で、結果をすべて「連想配列の配列」として
// 一度に取得します。1行が1つの連想配列(例: ["id" => 1, "name" => "web-01", ...])
// になります。
$servers = $selectStatement->fetchAll(PDO::FETCH_ASSOC);

echo '現在登録されているサーバー(' . count($servers) . '件):' . PHP_EOL;
foreach ($servers as $server) {
    echo "  id={$server['id']}: {$server['name']} / {$server['ip']} / status={$server['status']}" . PHP_EOL;
}
echo PHP_EOL;


echo '===== 5. 1件をUPDATEしてstatusを変更する =====' . PHP_EOL;

// -----------------------------------------------------------------
// UPDATE文でも、変更したい条件(ここでは name)や値(ここでは
// 新しいstatus)を "?" のプレースホルダーにして、execute() の
// 配列で値をあてはめます。順番は SQL文中の "?" の出現順と一致させます。
// -----------------------------------------------------------------
$updateStatement = $pdo->prepare(
    'UPDATE servers SET status = ? WHERE name = ?'
);
$updateStatement->execute(['stopped', 'web-02']);

// rowCount() で、直前のUPDATE/DELETEによって何件のデータが
// 変更されたかを確認できます。
$updatedCount = $updateStatement->rowCount();
echo "web-02 の status を 'stopped' に変更しました({$updatedCount}件更新)。" . PHP_EOL;
echo PHP_EOL;


echo '===== 6. 1件をDELETEして削除する =====' . PHP_EOL;

$deleteStatement = $pdo->prepare('DELETE FROM servers WHERE name = ?');
$deleteStatement->execute(['db-01']);

$deletedCount = $deleteStatement->rowCount();
echo "db-01 を削除しました({$deletedCount}件削除)。" . PHP_EOL;
echo PHP_EOL;


echo '===== 7. 更新後の状態を確認する =====' . PHP_EOL;

// 同じprepare済みの $selectStatement をもう一度execute()すれば、
// 最新のデータを取得し直すことができます。
$selectStatement->execute();
$serversAfter = $selectStatement->fetchAll(PDO::FETCH_ASSOC);

echo '更新・削除後に残っているサーバー(' . count($serversAfter) . '件):' . PHP_EOL;
foreach ($serversAfter as $server) {
    echo "  id={$server['id']}: {$server['name']} / {$server['ip']} / status={$server['status']}" . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 8. 後片付け: データベースファイルを削除する
// ---------------------------------------------------------------------
// この演習では「実行するたびに毎回同じ結果になる」ようにしたいため、
// スクリプトの最後に servers.db を削除しておきます。
// PDOのオブジェクトを null にして接続を明示的に手放してから
// unlink() でファイルを削除します(接続を残したままファイルを
// 削除しようとすると、環境によっては削除に失敗することがあるためです)。
$pdo = null;
if (file_exists($dbPath)) {
    unlink($dbPath);
}
echo "データベースファイルを削除しました: {$dbPath}" . PHP_EOL;


// =======================================================================
// MySQLに接続する場合について
// =======================================================================
// ここまで、PDOのSQLiteドライバを使ってCRUD操作(登録・参照・更新・削除)
// の一連の流れを実装してきました。
//
// もし本物のMySQLサーバーに接続したい場合、変更が必要なのは
// 「接続時のDSNとユーザー名・パスワード」だけです。
// prepare() や execute()、fetchAll() などの書き方は
// SQLiteのときとまったく同じまま使うことができます。
//
//   // SQLiteのとき
//   $pdo = new PDO('sqlite:' . __DIR__ . '/servers.db');
//
//   // MySQLに接続する場合
//   $pdo = new PDO(
//       'mysql:host=localhost;dbname=servers_db;charset=utf8mb4',
//       'ユーザー名',
//       'パスワード'
//   );
//
// DSNの "mysql:host=localhost;dbname=servers_db;charset=utf8mb4" は、
// 「MySQLドライバを使って、localhost上の servers_db という
// データベースに、文字コード utf8mb4 で接続する」という意味です。
// ユーザー名とパスワードは new PDO() の第2引数・第3引数として渡します。
// (SQLiteはファイルそのものがデータベースなので、この2つは
// 不要でしたが、MySQLのようなサーバー型データベースでは、
// 誰がどのデータベースにアクセスできるかを管理するために
// ユーザー名とパスワードによる認証が必要になります。)
//
// このように、PDOを使っておくと「データベースの種類が変わっても、
// 接続部分の数行を書き換えるだけで、それ以降のコード(SQL文の実行や
// 結果の取得の書き方)はほとんど変更せずに済む」というのが、
// PDOを使う大きなメリットです。
// =======================================================================
