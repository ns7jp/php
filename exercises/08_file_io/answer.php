<?php

// =====================================================================
// 演習08: ファイル読み書き
// =====================================================================
// このファイルは模範解答です。
// - fopen/fread(fgets)/fclose を使った基本的なファイル操作の流れ
// - file_get_contents / file_put_contents を使った手軽なファイル操作
// - file_exists によるファイルの存在確認
// - key=value 形式の設定ファイルを連想配列に変換する処理
// - FILE_APPEND を使ったログの追記
// を、実際に動くコードで確認していきます。
// =====================================================================


// ---------------------------------------------------------------------
// 0. パスを準備する
// ---------------------------------------------------------------------
// "config.txt" のような相対パスをそのまま使うと、
// phpコマンドを実行したときの「カレントディレクトリ」によって
// 参照先が変わってしまいます。
// たとえば別のディレクトリから
//   php exercises/08_file_io/answer.php
// のように実行した場合、"config.txt" だけでは見つけられません。
//
// __DIR__ は「このPHPファイル自身が置かれているディレクトリの
// 絶対パス」を表す特別な定数です。__DIR__ を使ってパスを組み立てると、
// どこから実行してもファイルの場所がぶれずに済みます。
$configPath = __DIR__ . '/config.txt';
$logPath = __DIR__ . '/app.log';


// ---------------------------------------------------------------------
// 1. loadConfig(): 設定ファイルを読み込んで連想配列に変換する関数
// ---------------------------------------------------------------------
/**
 * key=value 形式の設定ファイルを読み込み、連想配列に変換する。
 *
 * 例: "host=localhost" という行は ["host" => "localhost"] に変換される。
 *
 * @param string $path 設定ファイルのパス
 * @return array 読み込んだ設定(キー => 値)。ファイルが存在しない場合は空配列。
 */
function loadConfig(string $path): array
{
    // ファイルを開こうとする前に、そもそも存在するかどうかを
    // file_exists() で確認します。存在しないファイルに対して
    // file() や fopen() を呼び出すと警告(Warning)が出てしまうため、
    // 事前にチェックしておくのが安全な書き方です。
    if (!file_exists($path)) {
        echo "設定ファイルが見つかりません: {$path}" . PHP_EOL;
        return [];
    }

    // file() 関数は、ファイルの中身を「1行ずつの配列」として
    // まとめて読み込んでくれる便利な関数です。
    // 第2引数のフラグには、以下の2つを指定しています。
    //   FILE_IGNORE_NEW_LINES … 各行の末尾に付く改行コード(\nなど)を
    //                            自動的に取り除いてくれる
    //   FILE_SKIP_EMPTY_LINES … 空行を結果の配列に含めない
    // このおかげで、あとから trim() で改行を除去する手間が省けます。
    $lines = file($path, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES);

    $config = [];

    foreach ($lines as $line) {
        // explode("=", $line, 2) のように第3引数へ 2 を渡すと、
        // 「最初に見つかった "=" のところで1回だけ分割する」という
        // 意味になります。
        // こうしておくと、もし値の中に "=" が含まれる場合
        // (例: "url=http://example.com/?a=1") でも、
        // キーと値の2つにきちんと分けることができます。
        $parts = explode('=', $line, 2);

        // "=" を含まない壊れた行(コメント行や空行の残骸など)は
        // 無視してスキップします。
        if (count($parts) < 2) {
            continue;
        }

        [$key, $value] = $parts;

        // trim() でキーと値の前後にある余計な空白を取り除いてから、
        // 連想配列に格納します。
        $config[trim($key)] = trim($value);
    }

    return $config;
}


// ---------------------------------------------------------------------
// 2. writeLog(): メッセージをログファイルに追記する関数
// ---------------------------------------------------------------------
/**
 * 実行日時付きのメッセージを app.log に追記する簡易ロガー。
 *
 * @param string $message ログに残したいメッセージ
 */
function writeLog(string $message): void
{
    // ログファイルのパスも __DIR__ を使って組み立てます。
    $logPath = __DIR__ . '/app.log';

    // 日時を先頭に付けておくと、「いつ実行されたログなのか」が
    // あとから見返したときに分かりやすくなります。
    // date('Y-m-d H:i:s') は "2024-01-15 10:23:45" のような
    // 形式の文字列を返します。
    $line = '[' . date('Y-m-d H:i:s') . '] ' . $message . PHP_EOL;

    // ここがこの関数でいちばん重要なポイントです。
    // file_put_contents($path, $data, FILE_APPEND) のように
    // 第3引数へ FILE_APPEND を指定すると、既存のファイルの内容を
    // 消さずに「末尾に追記」してくれます。
    //
    // もし FILE_APPEND を指定しなかった場合、file_put_contents() は
    // 呼び出すたびにファイルの中身を丸ごと新しい内容で「上書き」して
    // しまうため、実行するたびに過去のログが消えてしまいます。
    file_put_contents($logPath, $line, FILE_APPEND);
}


// ---------------------------------------------------------------------
// 3. file_exists() で設定ファイルの存在を確認する
// ---------------------------------------------------------------------
echo "===== 1. file_exists() による存在確認 =====" . PHP_EOL;

if (file_exists($configPath)) {
    echo "config.txt が見つかりました: {$configPath}" . PHP_EOL;
} else {
    // このサンプルでは config.txt を同梱しているので、通常はこちらの
    // 分岐には入りません。もしファイルを削除したりリネームしたりすると
    // この分岐が実行されます。
    echo "config.txt が見つかりません: {$configPath}" . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 4. loadConfig() で設定ファイルを連想配列として読み込む
// ---------------------------------------------------------------------
echo "===== 2. loadConfig() による設定の読み込み =====" . PHP_EOL;

$config = loadConfig($configPath);

foreach ($config as $key => $value) {
    echo "{$key} = {$value}" . PHP_EOL;
}
echo PHP_EOL;

// 連想配列に変換してしまえば、あとは普通のPHPの配列として
// 自由に扱うことができます。
// "??" 演算子(null合体演算子)を使うと、「キーが存在しなかった場合の
// デフォルト値」を簡潔に指定できます。
$host = $config['host'] ?? '不明';
$port = $config['port'] ?? '不明';
$timeout = $config['timeout'] ?? '不明';

echo "接続先: {$host}:{$port}(タイムアウト: {$timeout}秒)" . PHP_EOL;
echo PHP_EOL;


// ---------------------------------------------------------------------
// 5. fopen / fgets / fclose を使って1行ずつ読み込む(低レベルな方法)
// ---------------------------------------------------------------------
echo "===== 3. fopen/fgets/fclose による1行ずつの読み込み =====" . PHP_EOL;

// fopen(パス, モード) でファイルを開きます。
// 'r' は「読み込み専用(read)」を意味するモードです。
// 成功するとファイルハンドル(このファイルを操作するための目印のような
// もの)が返り、失敗すると false が返ります。
$handle = fopen($configPath, 'r');

if ($handle === false) {
    echo "ファイルを開けませんでした。" . PHP_EOL;
} else {
    $lineNumber = 1;

    // feof($handle) は「ファイルポインタが末尾(End Of File)に
    // 達したかどうか」を判定する関数です。
    // while (!feof($handle)) と書くことで、「ファイルの終わりに
    // 達するまで繰り返す」というループになります。
    while (!feof($handle)) {
        // fgets($handle) は、ファイルポインタの位置から
        // 改行までの1行分を読み込み、ポインタを次の行の先頭に
        // 進めてくれます。
        $line = fgets($handle);

        // ファイルの末尾に達したときなど、fgets() が false を
        // 返すことがあります。また、空行(改行だけの行)も
        // 表示する必要がないためスキップします。
        if ($line === false || trim($line) === '') {
            continue;
        }

        echo "{$lineNumber}行目: " . trim($line) . PHP_EOL;
        $lineNumber++;
    }

    // fopen() で開いたファイルは、使い終わったら必ず fclose() で
    // 閉じましょう。閉じ忘れると、ファイルが他のプログラムから
    // 開けなくなったり、システムが管理できる「開いているファイルの数」
    // の上限に達してしまったりする原因になります。
    // (file_get_contents() や file() のような関数は、内部で自動的に
    // ファイルを閉じてくれるため、fclose() を呼び出す必要はありません)
    fclose($handle);
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 6. file_get_contents() でファイルの中身をまとめて読む(手軽な方法)
// ---------------------------------------------------------------------
echo "===== 4. file_get_contents() による一括読み込み =====" . PHP_EOL;

// file_get_contents() は、fopen -> (fread を繰り返す) -> fclose という
// 一連の流れを1行で済ませてくれる、非常によく使われる関数です。
// ファイルの中身をまるごと1つの文字列として取得できます。
$rawContents = file_get_contents($configPath);

echo "config.txt の中身(生データ):" . PHP_EOL;
echo $rawContents;
echo PHP_EOL;


// ---------------------------------------------------------------------
// 7. writeLog() でログファイルに追記する
// ---------------------------------------------------------------------
echo "===== 5. writeLog() によるログの追記(FILE_APPEND) =====" . PHP_EOL;

writeLog('answer.php を実行し、config.txt を読み込みました。');
writeLog("読み込んだ設定: host={$host}, port={$port}, timeout={$timeout}");

echo "app.log にログを2行追記しました。" . PHP_EOL;
echo "このファイル(answer.php)を実行するたびに、FILE_APPEND のおかげで" . PHP_EOL;
echo "app.log の行数が増えていきます。何度か実行して確認してみましょう。" . PHP_EOL;
echo PHP_EOL;

// 参考として、file_get_contents() を使って app.log の現在の中身を
// そのまま表示してみます。実行するたびにこの表示が増えていくはずです。
echo "----- 現在の app.log の中身 -----" . PHP_EOL;
echo file_get_contents($logPath);
