// ---------------------------------------------------------------------
// 0. 画面表示設定(ini_set・error_reporting) ― 開発環境 と 本番環境の違い
// ---------------------------------------------------------------------
// PHPには、「エラーが発生したときに、画面に表示するかどうか」や
// 「どのレベルのエラーを検知の対象にするか」を切り替える設定があります。
// これらは php.ini というファイルであらかじめ設定できますが、
// ini_set() を使うと、プログラムの中からも一時的に変更できます。
//
// ---- 開発環境(自分のPCで動作確認しているとき)向けの設定例 ----
// 開発中は、エラーの詳細をその場で画面に表示してもらったほうが
// 「どこで何が間違っているか」をすぐに確認できて便利です。
//
//   ini_set('display_errors', '1');   // 画面にエラーを表示する
//   error_reporting(E_ALL);           // 警告(Warning)や通知(Notice)も含め、
//                                      // すべてのエラーを検知の対象にする
//
// ---- 本番環境(実際に公開しているWebサーバー)相当の設定例 ----
// 本番環境で画面にエラーの詳細(ファイルパスやSQL文など)を表示してしまうと、
// サーバー内部の情報が外部に漏れてしまい、攻撃の手がかりを与える
// 危険があります。そのため、本番環境では
//   ・エラー自体は「検知」はする(見逃さない)
//   ・ただし、画面には表示せず、ログファイルにだけ記録する
// という設定にするのが鉄則です。この演習では、実際に下の設定を
// 有効にして、その動きを体験してみます。
ini_set('display_errors', '0');   // 画面にはエラーを表示しない(本番相当)
error_reporting(E_ALL);           // ただし、エラーの検知そのものは行う


// ---------------------------------------------------------------------
// ログファイルのパスを定数として定義しておく
// ---------------------------------------------------------------------
// __DIR__ は「このPHPファイルが置かれているディレクトリの絶対パス」を
// 表す特別な定数です。__DIR__ を使ってパスを組み立てておくと、
// このスクリプトをどこから実行しても(どのディレクトリからphpコマンドを
// 打っても)、常に同じ場所にある error.log を指すようになります。
define('LOG_FILE', __DIR__ . '/error.log');


// ---------------------------------------------------------------------
// 1. 独自の例外クラスを作る(class ... extends Exception系)
// ---------------------------------------------------------------------
// PHPにはあらかじめ Exception クラスや、それを継承した
// RuntimeException・InvalidArgumentException などが用意されています。
// さらに自分たちで「独自の例外クラス」を作ることもできます。
//
// 「設定ファイルが見つからない」という、特定の種類のエラー専用の
// 例外クラスを用意しておくと、catch するときに
//   catch (ConfigFileNotFoundException $e) { ... }
// のように「どんな種類のエラーが起きたか」で処理を分けやすくなります。
// (単に catch (Exception $e) とだけ書くと、本来まったく別の原因で
//  起きたエラーまで、同じ catch ブロックで受け止めてしまいます)
//
// ここでは、「実行時に問題が起きたことを表す」意味を持つ
// 標準の RuntimeException クラスを継承して作ります。
class ConfigFileNotFoundException extends RuntimeException
{
    // 「どの設定ファイルが見つからなかったのか」を、あとから
    // 取り出せるように専用のプロパティとして持たせておきます。
    private string $configPath;

    public function __construct(string $configPath)
    {
        // 画面には出さない前提の、開発者向けの詳細なメッセージを組み立てます。
        // (実際にファイルが見つからなかったパスを含めておくことで、
        //  ログを見た人がすぐに原因を特定できるようにします)
        $message = sprintf('設定ファイルが見つかりません: %s', $configPath);

        // 親クラス(RuntimeException、さらにその親のException)の
        // コンストラクタを呼び出し、$message を「例外のメッセージ」として
        // 登録します。これにより、あとから $e->getMessage() でこの
        // メッセージを取り出せるようになります。
        parent::__construct($message);

        $this->configPath = $configPath;
    }

    // どのファイルが原因だったのかを、呼び出し元が個別に取得したい場合の
    // ための getter です。ログの出力方法を細かく変えたいときなどに使えます。
    public function getConfigPath(): string
    {
        return $this->configPath;
    }
}


// ---------------------------------------------------------------------
// 2. 設定ファイルを読み込む関数 loadConfig() を作る(throw)
// ---------------------------------------------------------------------
// 指定されたパスの設定ファイル(INI形式)を読み込み、
// 連想配列として返す関数です。ファイルが存在しない場合は、
// 呼び出し元に「エラーが起きたこと」を伝えるために、
// 上で定義した独自の例外を throw(投げる) します。
function loadConfig(string $path): array
{
    // file_exists() は、指定したパスにファイル(またはディレクトリ)が
    // 実際に存在するかどうかを true/false で返す関数です。
    // 「設定ファイルを配置し忘れた」「デプロイ時にファイルが漏れた」
    // といったトラブルは実務でもよく起こるため、ファイルを開く前に
    // 必ず存在確認をしておくのは基本的な作法です。
    if (!file_exists($path)) {
        // throw は「ここでエラーが起きた」ということをプログラムに
        // 知らせるための構文です。throw されると、その場で通常の処理は
        // 中断され、呼び出し元にある catch ブロックまで一気に処理が
        // 移動します(この関数の残りの行や、呼び出し元の続きの行は
        // 実行されません)。
        throw new ConfigFileNotFoundException($path);
    }

    // parse_ini_file() は、INI形式の設定ファイルを読み込んで、
    // 連想配列に変換してくれるPHPの標準関数です。
    // 第2引数を true にすると、[app] や [database] のような
    // 「セクション」ごとに配列を入れ子にして読み込んでくれます。
    $config = parse_ini_file($path, true);

    // parse_ini_file() は、ファイルの中身がINI形式として壊れている場合
    // などに false を返します。この演習では詳しく扱いませんが、
    // 実務ではこのような「ファイルはあるが、中身が壊れている」ケースも
    // 考慮してエラー処理を行います。今回は簡略化のため、同じ例外クラスを
    // 使って「設定を読み込めなかった」ことを伝えます。
    if ($config === false) {
        throw new ConfigFileNotFoundException($path);
    }

    return $config;
}


// ---------------------------------------------------------------------
// 3. 設定ファイルの読み込みを試し、try/catch/finallyで結果を処理する
// ---------------------------------------------------------------------
// 「設定ファイルを読み込んで結果を表示する」という一連の流れを
// 関数にまとめておくことで、成功パターン・失敗パターンの両方を
// 同じロジックで試すことができます。
function demoConfigLoad(string $label, string $path): void
{
    echo "----- {$label} -----" . PHP_EOL;

    // try ブロックの中には、「エラーが起きるかもしれない処理」を書きます。
    try {
        // loadConfig() がファイルを見つけられなかった場合、
        // この行で ConfigFileNotFoundException が throw され、
        // try ブロックの残り(この下の echo や print_r)は実行されずに、
        // 下の catch ブロックまで処理がジャンプします。
        $config = loadConfig($path);

        echo '設定ファイルの読み込みに成功しました。' . PHP_EOL;
        echo '読み込んだ内容:' . PHP_EOL;
        print_r($config);
    } catch (ConfigFileNotFoundException $e) {
        // catch (型 $変数名) と書くことで、「その型の例外が
        // throw されたときだけ」この中の処理を実行できます。
        // ここでは ConfigFileNotFoundException だけを捕まえています。

        // ---- 画面向け: 利用者に見せる、詳細を伏せたメッセージ ----
        // 「画面にエラーの詳細(ファイルパスなど)を出さない」のが
        // 本番環境での鉄則です。ここではファイルパスなどの内部情報を
        // 含まない、一般的な案内文だけを画面に表示します。
        echo '設定ファイルの読み込みに失敗しました。しばらくしてから再度お試しください。' . PHP_EOL;

        // ---- ログ向け: 開発者・運用担当者のための詳細な記録 ----
        // 画面には出さない代わりに、「いつ」「何が」起きたのかを
        // 必ずログファイルに残しておきます。こうしておけば、
        // 後から運用担当者やエンジニアがログを確認して、
        // 原因を調査・対応できます。
        $timestamp = date('Y-m-d H:i:s');
        $logMessage = sprintf(
            '[%s] ConfigFileNotFoundException: %s',
            $timestamp,
            $e->getMessage()
        );

        // error_log(書き込む文字列, メッセージの送り先の種類, 送り先)
        // 第2引数に 3 を指定すると、「第3引数で指定したファイルに、
        // メッセージを追記する」という動作になります。
        // (改行は自動では付かないため、PHP_EOL を自分で付け足します)
        error_log($logMessage . PHP_EOL, 3, LOG_FILE);
    } finally {
        // finally ブロックは、
        //   ・try が最後まで成功した場合
        //   ・catch で例外を捕まえた場合
        // のどちらであっても、必ず実行されるブロックです。
        //
        // 「この設定ファイルの読み込み処理はここで終わった」という
        // 記録を、成功・失敗にかかわらず必ずログに残しておくと、
        // 後から一連の処理の流れを追いかけやすくなります。
        // (「開始したのに終了ログがない」という状態から、
        //  処理の途中で予期せず落ちたことに気づける、といった使い方もできます)
        $timestamp = date('Y-m-d H:i:s');
        $logMessage = sprintf(
            '[%s] 処理終了: %s の読み込み処理を終えました。',
            $timestamp,
            $label
        );
        error_log($logMessage . PHP_EOL, 3, LOG_FILE);
    }

    echo PHP_EOL;
}


// ---------------------------------------------------------------------
// 4. 実際に2つのパターンを試してみる
// ---------------------------------------------------------------------
echo '===== 演習14: 例外処理とエラーログ =====' . PHP_EOL . PHP_EOL;

// パターン1: 実際に存在する設定ファイルを読み込む(成功パターン)
// このディレクトリに用意されている config_sample.ini を読み込みます。
demoConfigLoad('存在する設定ファイル', __DIR__ . '/config_sample.ini');

// パターン2: 存在しない設定ファイルを読み込もうとする(失敗パターン)
// config_missing.ini というファイルは、このディレクトリにわざと
// 用意していません。file_exists() が false を返すことで、
// ConfigFileNotFoundException が throw されるはずです。
demoConfigLoad('存在しない設定ファイル', __DIR__ . '/config_missing.ini');


// ---------------------------------------------------------------------
// 5. (確認用)error.log に記録された内容を表示する
// ---------------------------------------------------------------------
// 本来、本番環境ではログファイルの中身を画面に表示することは
// ほとんどありません(ログはサーバー管理者がサーバー上で直接確認するものです)。
// ここでは、「本当にログファイルへ記録できているか」を学習用に
// その場で確認できるように、あえて画面にも表示しています。
echo '===== error.log の中身(学習用の確認表示) =====' . PHP_EOL;
if (file_exists(LOG_FILE)) {
    echo file_get_contents(LOG_FILE);
} else {
    // 通常はここには来ませんが、万が一ログファイルへの書き込みに
    // 失敗していた場合のための保険の表示です。
    echo '(まだログファイルが作成されていません)' . PHP_EOL;
}
