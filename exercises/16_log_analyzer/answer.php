<?php

// =====================================================================
// 演習16: 簡易ログ解析ツール (模範解答)
// =====================================================================
// このファイルは、practice.php の TODO をすべて実装した「完成版」です。
// 上から順番にコメントを読みながら、どんな考え方でコードを書いているか
// 確認してみてください。
//
// この演習では、同じディレクトリにある access_sample.log という
// ダミーのアクセスログファイル(Combined Log Format風)を読み込み、
// 正規表現でIPアドレスやステータスコードなどを取り出したうえで、
// 「ステータスコードごとの件数」「アクセスの多いIPアドレスの
// ランキング」を集計して表示します。
// =====================================================================

echo "===== 演習16: 簡易ログ解析ツール =====" . PHP_EOL;
echo PHP_EOL;


// ---------------------------------------------------------------------
// 0. ログファイルのパスと、解析に使う正規表現パターンを用意する
// ---------------------------------------------------------------------
// __DIR__ は「このPHPファイルが置かれているディレクトリ」を表す
// マジック定数です。実行するときのカレントディレクトリに関係なく、
// 常に同じ場所にある access_sample.log を読み込めるようにしています。
$logFilePath = __DIR__ . "/access_sample.log";

// Combined Log Format(Apache/Nginxでよく使われるアクセスログの形式)は、
// 例えば次のような1行で構成されています。
//   192.168.1.10 - - [15/Jan/2024:10:23:45 +0900] "GET /index.php HTTP/1.1" 200 1234
// このうち、今回の演習で取り出したいのは次の6つの情報です。
//   1. IPアドレス   : 192.168.1.10
//   2. 日時         : 15/Jan/2024:10:23:45 +0900
//   3. メソッド     : GET
//   4. パス         : /index.php
//   5. ステータスコード: 200
//   6. バイト数     : 1234
// これを取り出すための正規表現が次のパターンです。
//   ^(\S+)          -> 行頭から空白以外が続く部分(IPアドレス)をグループ1として取得
//   \S+ \S+         -> 続く2つの項目("-" "-" の部分)は使わないので読み飛ばす
//   \[([^\]]+)\]    -> "[" と "]" で囲まれた部分(日時)をグループ2として取得
//                      ([^\]]+ は「']' 以外の文字が1文字以上」という意味)
//   "(\S+) (\S+)    -> ダブルクォートの直後にある「メソッド」と「パス」を
//                      それぞれグループ3・グループ4として取得
//   [^"]+"          -> 残りの " HTTP/1.1" の部分(ダブルクォートで閉じるまで)を読み飛ばす
//   (\d{3})         -> 3桁の数字(ステータスコード)をグループ5として取得
//   (\d+)           -> 1桁以上の数字(バイト数)をグループ6として取得
//
// 末尾の "m" は「マルチラインモード」を有効にする修飾子です。
// 1行ずつ preg_match() に渡す場合、その文字列自体に改行が含まれて
// いないので "m" があってもなくても結果は変わりません。しかし
// 6.で行うように「ファイル全体(複数行を含む1つの長い文字列)」に
// 対して preg_match_all() を使う場合、"m" を付けておかないと
// 先頭の "^" が「文字列全体の一番最初」にしかマッチしなくなり、
// 2行目以降がうまく拾えなくなってしまいます。"m" を付けることで、
// "^" が「(改行のたびに始まる)各行の先頭」にマッチするようになります。
$pattern = '/^(\S+) \S+ \S+ \[([^\]]+)\] "(\S+) (\S+) [^"]+" (\d{3}) (\d+)/m';


// ---------------------------------------------------------------------
// 1. ログファイルを読み込む
// ---------------------------------------------------------------------
// file() 関数は、ファイルの中身を「1行ずつの要素を持つ配列」として
// 読み込んでくれる便利な関数です。
//   FILE_IGNORE_NEW_LINES -> 各行の末尾についている改行文字(\n)を
//                            取り除いた状態で配列に入れる
//   FILE_SKIP_EMPTY_LINES -> 中身が空の行(空行)を配列に含めない
// という2つのフラグを指定することで、後の正規表現処理がしやすい、
// 綺麗な状態の配列にしています。
echo "----- 1. ログファイルを読み込む -----" . PHP_EOL;

$lines = file($logFilePath, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES);

echo "読み込んだ行数: " . count($lines) . "行" . PHP_EOL;
echo PHP_EOL;


// ---------------------------------------------------------------------
// 2. まずは1行だけで正規表現をテストしてみる
// ---------------------------------------------------------------------
// 正規表現は、少しでも書き方が実際のログの形式とずれていると
// マッチしなくなってしまいます(例えば空白の数が違う、記号を
// 忘れている、など)。そのため、いきなり全部の行を処理するのではなく、
// まずは1行だけを使ってパターンが正しく書けているかを確認する、
// というのがデバッグの定石です。
echo "----- 2. 正規表現を1行だけでテストする -----" . PHP_EOL;

$testLine = $lines[0];
echo "テスト対象の行:" . PHP_EOL;
echo "  {$testLine}" . PHP_EOL;

// preg_match(パターン, 対象の文字列, 結果を格納する変数) は、
// パターンが対象の文字列にマッチするかどうかを調べる関数です。
// 戻り値は「マッチした回数(0か1)」で、マッチした場合は
// 第3引数に渡した変数(ここでは $testMatches)に、
//   $testMatches[0] -> マッチした部分全体
//   $testMatches[1] -> 1番目の()で囲んだグループ(今回はIPアドレス)
//   $testMatches[2] -> 2番目のグループ(日時)
//   ...
// というように、グループごとの文字列が配列として格納されます。
$testResult = preg_match($pattern, $testLine, $testMatches);

if ($testResult === 1) {
    echo "マッチ結果:" . PHP_EOL;
    echo "  IPアドレス     : {$testMatches[1]}" . PHP_EOL;
    echo "  日時           : {$testMatches[2]}" . PHP_EOL;
    echo "  メソッド       : {$testMatches[3]}" . PHP_EOL;
    echo "  パス           : {$testMatches[4]}" . PHP_EOL;
    echo "  ステータスコード: {$testMatches[5]}" . PHP_EOL;
    echo "  バイト数       : {$testMatches[6]}" . PHP_EOL;
} else {
    // ここに来る場合は、正規表現かログの形式のどちらかが
    // 想定と違っている可能性が高いです。
    echo "1行目のテストでマッチしませんでした。正規表現を見直してください。" . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 3. 全行を処理して、必要な情報を配列にまとめる
// ---------------------------------------------------------------------
// 2.でパターンが正しく書けていることが確認できたので、
// 今度は foreach で全行を1行ずつ処理していきます。
// 1行ごとに preg_match() を呼び出し、マッチした場合だけ
// 「1件分のログ情報」を連想配列として $records に追加していきます。
// (マッチしなかった行は、壊れたログ・想定外の形式の行として
//  件数だけ数えておき、あとで表示します)
echo "----- 3. 全行を解析する -----" . PHP_EOL;

$records = [];       // 解析に成功した1行ずつの情報を溜めていく配列
$unparsedCount = 0;  // 正規表現にマッチしなかった行の数

foreach ($lines as $line) {
    $matches = [];
    $isMatched = preg_match($pattern, $line, $matches);

    if ($isMatched === 1) {
        // $matches[1]〜$matches[6] を、意味の分かる名前をつけた
        // 連想配列にまとめて $records に追加します。
        // こうしておくと、あとの集計処理で $record["ip"] のように
        // 読みやすい名前でアクセスできます。
        $records[] = [
            "ip"       => $matches[1],
            "datetime" => $matches[2],
            "method"   => $matches[3],
            "path"     => $matches[4],
            "status"   => $matches[5],
            "bytes"    => (int) $matches[6],
        ];
    } else {
        $unparsedCount++;
    }
}

echo "解析に成功した行数  : " . count($records) . "行" . PHP_EOL;
echo "解析できなかった行数: {$unparsedCount}行" . PHP_EOL;
echo PHP_EOL;


// ---------------------------------------------------------------------
// 4. ステータスコードごとのアクセス数を集計する
// ---------------------------------------------------------------------
// ここで使うのが「連想配列をカウンタとして使う」というパターンです。
// $statusCounts[$status] = ($statusCounts[$status] ?? 0) + 1;
// という1行の意味は、
//   「$statusCounts[$status] がまだ存在しなければ 0 として扱い、
//    そこに1を足した値を、あらためて $statusCounts[$status] に
//    代入する」
// ということです。"??"(null合体演算子)を使うことで、
// 「まだ1度も出てきていないステータスコードかどうか」を
// 自分でif文を書いて調べなくても、安全に件数を増やしていけます。
echo "----- 4. ステータスコードごとの集計 -----" . PHP_EOL;

$statusCounts = [];

foreach ($records as $record) {
    $status = $record["status"];
    $statusCounts[$status] = ($statusCounts[$status] ?? 0) + 1;
}

// ksort() は連想配列を「キーの順番(ここではステータスコードの昇順)」
// に並び替える関数です。200, 301, 404, 500 のように見やすい順番で
// 表示するために使っています(集計そのものには必須ではありません)。
ksort($statusCounts);

foreach ($statusCounts as $status => $count) {
    echo "  {$status}: {$count}件" . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 5. IPアドレスごとのアクセス数を集計し、上位5件のランキングを作る
// ---------------------------------------------------------------------
// 考え方は4.のステータスコード集計とまったく同じです。
// 「IPアドレスをキーにしたカウンタ」を作り、出現するたびに+1します。
echo "----- 5. IPアドレスごとのアクセスランキング(上位5件) -----" . PHP_EOL;

$ipCounts = [];

foreach ($records as $record) {
    $ip = $record["ip"];
    $ipCounts[$ip] = ($ipCounts[$ip] ?? 0) + 1;
}

// arsort() は連想配列を「値の大きい順」に並び替える関数です。
// 似た名前の sort() や rsort() は、並び替えのときにキーを
// 0, 1, 2, ... に振り直してしまい、「どのIPアドレスの件数か」が
// 分からなくなってしまいます。arsort() は値で並び替えつつ、
// キー(ここではIPアドレス)との対応関係をそのまま保ってくれるので、
// 「アクセス数ランキング」のような集計処理に向いています。
arsort($ipCounts);

// array_slice(配列, 開始位置, 取得する件数, キーを保持するか) を使うと、
// 配列の一部分だけを切り出せます。4番目の引数に true を指定すると、
// 元の配列が持っていた文字列キー(IPアドレス)をそのまま保持したまま
// 切り出してくれます(数値キーの場合は明示的に true を指定しないと
// 0番から振り直されてしまうことがあるため、癖として true を
// 付けておくと安全です)。
$topIps = array_slice($ipCounts, 0, 5, true);

$rank = 1;
foreach ($topIps as $ip => $count) {
    echo "  {$rank}位: {$ip} ({$count}件)" . PHP_EOL;
    $rank++;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 6. preg_match_all() でファイル全体を一度に処理する(参考)
// ---------------------------------------------------------------------
// ここまでは preg_match() を「1行ずつ」呼び出してきました。
// これに対して preg_match_all() は、渡された文字列の中から
// パターンにマッチする部分を「すべて」まとめて探し出してくれる関数です。
// file_get_contents() でログファイル全体を1つの文字列として読み込み、
// その文字列全体に対して preg_match_all() を1回呼び出すだけで、
// 3.でforeachを回しながら1行ずつ集めたのと同じ数の結果が
// 得られることを確認してみましょう。
echo "----- 6. preg_match_allで全体を一括抽出する(参考) -----" . PHP_EOL;

$rawLogText = file_get_contents($logFilePath);

// preg_match_all() の第3引数には、preg_match() のような
// 「1件分の配列」ではなく、「グループごとに、マッチした数だけ
// 値が入った配列の配列」が格納されます。つまり、
//   $allMatches[0] -> マッチした部分全体の配列(1件目, 2件目, ...)
//   $allMatches[1] -> グループ1(IPアドレス)だけを集めた配列
//   $allMatches[5] -> グループ5(ステータスコード)だけを集めた配列
// のようになります。戻り値はマッチした「件数」です。
$matchCount = preg_match_all($pattern, $rawLogText, $allMatches);

echo "preg_match_allで一致した件数: {$matchCount}件" . PHP_EOL;
echo "(3.でforeach+preg_matchを使って集計した件数 " . count($records) . "件と一致していれば、"
    . "1行ずつ処理する方法と一括で処理する方法の結果が同じであることが確認できます)" . PHP_EOL;
echo PHP_EOL;

echo "===== 演習16はここまでです =====" . PHP_EOL;
