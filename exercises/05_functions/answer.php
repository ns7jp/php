// ---------------------------------------------------------------------
// 1. formatBytes() 関数を作る(デフォルト引数・型宣言)
// ---------------------------------------------------------------------
// バイト数(int)を受け取り、"1.5 KB" のように読みやすい単位の文字列(string)に
// 変換する関数です。
//
//   function formatBytes(int $bytes, int $precision = 2): string
//                        ^^^^^^^^^^  ^^^^^^^^^^^^^^^^^^  ^^^^^^^
//                        型宣言       デフォルト引数        戻り値の型宣言
//
// ・「int $bytes」のように引数名の前に型名を書くことを「型宣言(型ヒント)」と言います。
//   int以外の値(例えば文字列 "abc")を渡そうとすると、PHPがエラーとして
//   教えてくれるので、意図しないバグに早く気づけます。
// ・「int $precision = 2」のように「= 値」を付けると、その引数を省略して
//   呼び出したときに自動でその値が使われます。これを「デフォルト引数」と言います。
// ・関数名の後ろの「: string」は「戻り値の型宣言」です。この関数は必ず
//   string型の値を返す、とPHPに宣言しています。
function formatBytes(int $bytes, int $precision = 2): string
{
    // 1024ごとに繰り上がる単位を、小さい順に並べておきます。
    $units = ['B', 'KB', 'MB', 'GB', 'TB'];

    // 0バイト、またはマイナスの値が来た場合の安全対策です。
    // (0以下のときに log() を計算しようとすると、正しく計算できません)
    if ($bytes <= 0) {
        return '0 B';
    }

    // log($bytes, 1024) は「1024を何回掛けると $bytes になるか」を計算します。
    // 言い換えると「1024で何回割れるか」、つまり「どの単位を使うべきか」がわかります。
    // 例: 1024 -> 1(KB), 1048576 -> 2(MB), 1073741824 -> 3(GB)
    // 小数で返ってくるので、floor() で整数(小さいほうに切り捨て)にします。
    $power = (int) floor(log($bytes, 1024));

    // 非常に大きな値が来たときのために、$units配列の範囲を超えないようにします。
    // (例えば単位がTBより大きくなる場合でも、配列の末尾であるTBのまま表示します)
    $power = min($power, count($units) - 1);

    // バイト数を、求めた単位に応じて 1024^$power で割ります。
    // 例えば $power が 2(MB)なら、1024 * 1024 = 1,048,576 で割ることになります。
    // round() で小数点以下を $precision 桁に丸めて、見やすい数値にします。
    $value = round($bytes / (1024 ** $power), $precision);

    // 数値と単位をつなげた文字列を返します。
    return $value . ' ' . $units[$power];
}

echo "----- 1. formatBytes() でバイト数を変換 -----" . PHP_EOL;
echo "500 バイト                    => " . formatBytes(500) . PHP_EOL;
echo "1536 バイト                   => " . formatBytes(1536) . PHP_EOL;
echo "1048576 バイト                => " . formatBytes(1048576) . PHP_EOL;
echo "5368709120 バイト             => " . formatBytes(5368709120) . PHP_EOL;
// 第2引数(precision)を省略すると、デフォルト値の2桁で丸められます。
// ここではあえて 1 を指定して、デフォルト値を上書きしています。
echo "1234567 バイト(precision=1)  => " . formatBytes(1234567, 1) . PHP_EOL;
echo PHP_EOL;


// ---------------------------------------------------------------------
// 2. listServers() 関数を作る(可変長引数)
// ---------------------------------------------------------------------
// サーバー名をいくつでも受け取り、まとめて表示する関数です。
//
//   function listServers(string ...$names): void
//                         ^^^^^^^^^^^^^^^^
//                         可変長引数(型名の後ろに ... を付ける)
//
// 「string ...$names」のように「...」を付けて宣言すると、呼び出し時に
// 渡した引数の個数に関係なく(0個でも、1個でも、10個でも)受け取れるように
// なります。関数の中では $names が配列として扱えます。
//
// 「: void」は「この関数は値を返さない(画面に表示するだけ)」という意味の
// 戻り値の型宣言です。
function listServers(string ...$names): void
{
    // 引数が1つも渡されなかった場合は、専用のメッセージを表示します。
    if (count($names) === 0) {
        echo "監視対象: (サーバーが指定されていません)" . PHP_EOL;
        return; // ここで処理を終わらせる(この後のechoは実行しない)
    }

    // implode(区切り文字, 配列) を使うと、配列の要素を指定した文字で
    // つなげた1つの文字列にできます。
    // 例: implode(', ', ['web01', 'web02', 'db01']) => "web01, web02, db01"
    echo "監視対象: " . implode(', ', $names) . PHP_EOL;
}

echo "----- 2. listServers() で監視対象を表示 -----" . PHP_EOL;
// 3台分のサーバー名を渡す
listServers('web01', 'web02', 'db01');
// 1台だけ渡す
listServers('app01');
// あえて0個で呼び出す(可変長引数なので、引数なしでもエラーになりません)
listServers();
echo PHP_EOL;


// ---------------------------------------------------------------------
// 3. 変数のスコープ(有効範囲)を確認する
// ---------------------------------------------------------------------
// PHPの関数は、それぞれが独立した「スコープ(変数の有効範囲)」を持っています。
// 関数の外(グローバルスコープ)で定義した変数は、そのままでは関数の中から
// 見ることができません。これはバグを防ぐための重要な仕組みです。
echo "----- 3. 変数のスコープを確認する -----" . PHP_EOL;

$serviceName = "サーバー監視サービス"; // 関数の外(グローバルスコープ)で定義した変数

function showServiceNameBroken()
{
    // ここで $serviceName を使おうとしても、関数の外で定義した変数は
    // そのままでは見えません。isset() を使うと、警告(Warning)を出さずに
    // 「その変数が今この場所から見えるかどうか」を安全に確認できます。
    if (isset($serviceName)) {
        echo $serviceName . PHP_EOL;
    } else {
        echo "(見えません: 外側の \$serviceName はこの関数の中からは参照できません)" . PHP_EOL;
    }
}

showServiceNameBroken();

// 関数の外の値を関数の中で使いたいときは、「引数として渡す」のが基本の方法です。
// このように明示的に渡すことで、「この関数はどんな値を受け取って動くのか」が
// コードを読むだけでわかるようになり、他の変数と混同するミスも防げます。
function showServiceNameFixed(string $name): void
{
    echo $name . PHP_EOL;
}

// $serviceName を引数として渡すことで、関数の中でも正しく使えるようになります。
showServiceNameFixed($serviceName);
echo PHP_EOL;


// ---------------------------------------------------------------------
// 4. 無名関数とアロー関数(fn)で配列の値を2倍にする
// ---------------------------------------------------------------------
// 同じ「数値を2倍にする」処理を、無名関数とアロー関数の2通りの書き方で
// 用意し、array_map() に渡した結果が同じになることを確認します。
echo "----- 4. 無名関数とアロー関数で配列の値を2倍にする -----" . PHP_EOL;

$numbers = [1, 2, 3, 4, 5];
$multiplier = 2; // アロー関数がこの外側の変数を自動で取り込めることを確認するために使います

// 無名関数(function ($n) { ... } の形)は、名前を持たない関数です。
// 変数に代入したり、array_map() のように「関数を渡す必要がある場所」で
// その場で作って使ったりすることができます。
//
// 無名関数から「外側の変数($multiplier)」を使いたい場合は、
// use ($multiplier) のように明示的に書く必要がある点に注意してください。
$doubleAnonymous = function ($n) use ($multiplier) {
    return $n * $multiplier;
};

// アロー関数(fn(引数) => 式 の形)は、無名関数をさらに短く書ける記法です。
// 「return」を書かず、式の結果がそのまま戻り値になります。
// 無名関数と大きく違う点として、use() を書かなくても外側の変数
// ($multiplier)を自動的に取り込んで使うことができます。
$doubleArrow = fn ($n) => $n * $multiplier;

// array_map(コールバック関数, 配列) は、配列の全要素にコールバック関数を
// 適用し、変換後の値をまとめた新しい配列を返します。
// ここでは、それぞれの関数を渡して、結果を比較しています。
$resultAnonymous = array_map($doubleAnonymous, $numbers);
$resultArrow = array_map($doubleArrow, $numbers);

echo "元の配列          : " . implode(', ', $numbers) . PHP_EOL;
echo "無名関数での結果  : " . implode(', ', $resultAnonymous) . PHP_EOL;
echo "アロー関数での結果: " . implode(', ', $resultArrow) . PHP_EOL;

// 無名関数とアロー関数、どちらも同じ結果になることを確認します。
// (=== で比較すると、配列の中身と並び順まで含めて完全に一致するかを判定できます)
if ($resultAnonymous === $resultArrow) {
    echo "=> 無名関数とアロー関数の結果は一致しました。" . PHP_EOL;
} else {
    echo "=> 無名関数とアロー関数の結果が一致しませんでした。" . PHP_EOL;
}
