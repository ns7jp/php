// ---------------------------------------------------------------------
// 0. $_GET / $_POST をCLI用にシミュレートする
// ---------------------------------------------------------------------
// $_GET と $_POST は、本来はWebブラウザからのリクエストに応じて
// PHPが自動的に用意してくれる「スーパーグローバル変数」です。
//
//   - $_GET  : URLの "?key=value" の部分(クエリ文字列)から作られる値。
//              ページの表示内容を切り替えたり、どのデータを対象にするかを
//              指定したりするのによく使われます。
//              例) サーバー一覧画面の「編集」リンクが
//                  edit.php?id=5 のようなURLになっていて、
//                  そのリンクをクリックすると $_GET["id"] に "5" が入る。
//
//   - $_POST : <form method="post"> で送信されたフォームの入力内容。
//              サーバー側のデータを変更する(新規登録・更新・削除など)
//              処理を行うときによく使われます。
//              例) 「登録する」ボタンを押すと、フォームの入力内容が
//                  $_POST に入った状態でサーバーに送信される。
//
// つまり「どのデータを見る/操作するか(GET)」と
// 「実際に送信されたデータの中身(POST)」という役割の違いがあります。
//
// この演習ではブラウザやWebサーバーを使わず、CLI(コマンドライン)だけで
// 動作確認したいので、代わりにこの2つの変数へ直接配列を代入して
// 「あたかもリクエストが送られてきたかのように」シミュレートします。
// (実際のWebアプリケーションでは、この代入処理は不要です。
//  PHPが自動的に $_GET・$_POST を用意してくれます)
$_GET = [
    "id" => "5",
];

$_POST = [
    "hostname" => "web01",
    "ip"       => "192.168.1.10",
    "port"     => "8080",
];


// ---------------------------------------------------------------------
// 1. $_GET の値を表示する(XSS対策の練習)
// ---------------------------------------------------------------------
// $_GET や $_POST の値は「外部(ユーザーの入力やURL)から渡された値」
// なので、どんな文字列が入っているか分かりません。
// 悪意のある人が、URLの id パラメータに <script> のようなHTMLタグを
// 埋め込んでくる可能性もゼロではありません。
//
// そのため、画面(HTML)に表示する前提のデータは、
// htmlspecialchars() を通してから出力するのが基本です。
// htmlspecialchars() は、次のようにHTMLタグとして解釈されてしまう
// 特殊な文字を、無害な文字列(HTMLエンティティ)に変換します。
//   <  ->  &lt;
//   >  ->  &gt;
//   "  ->  &quot;
//   '  ->  &#039;
//   &  ->  &amp;
echo "----- 1. GETパラメータの表示 -----" . PHP_EOL;

$editTargetId = htmlspecialchars($_GET["id"]);

echo "編集対象のサーバーID: {$editTargetId}" . PHP_EOL;
echo PHP_EOL;


// ---------------------------------------------------------------------
// 2. バリデーション対象の値を取り出す
// ---------------------------------------------------------------------
// $_POST から、チェックしたい3つの値を取り出しておきます。
// (実際のフォームでは、キー自体が存在しないこともあるため、
//  本来は $_POST["hostname"] ?? "" のように「存在しない場合の初期値」も
//  考慮しますが、この演習では説明をシンプルにするため
//  常にキーが存在する前提で進めます)
$hostname = $_POST["hostname"];
$ip = $_POST["ip"];
$port = $_POST["port"];

echo "----- 送信された内容(未チェックの状態) -----" . PHP_EOL;
echo "hostname: {$hostname}" . PHP_EOL;
echo "ip      : {$ip}" . PHP_EOL;
echo "port    : {$port}" . PHP_EOL;
echo PHP_EOL;

// エラーメッセージをためていくための配列です。
// 「1つエラーが見つかったら、その場で処理を止めて表示する」のではなく、
// 「全部の項目を最後までチェックしてから、まとめて結果を伝える」ほうが
// ユーザーにとって親切なフォームになります。
// (一度に1つのエラーしか教えてもらえないと、直しては送信し、
//  また別のエラーが出て…と何度もやり取りが発生してしまいます)
$errors = [];


// ---------------------------------------------------------------------
// 3. ホスト名の必須チェック
// ---------------------------------------------------------------------
// empty($value) は、次のいずれかに当てはまる場合に true を返す関数です。
//   - 変数が定義されていない
//   - 空文字列 "" である
//   - null である
//   - 数値の 0 や 文字列の "0" である
//   - 空配列 [] である
// ここでは「ホスト名が1文字も入力されていないか」をチェックするために
// 使っています。
echo "----- 2. ホスト名のチェック -----" . PHP_EOL;

if (empty($hostname)) {
    $errors[] = "ホスト名を入力してください。";
    echo "NG: ホスト名が空です。" . PHP_EOL;
} else {
    echo "OK: ホスト名が入力されています。" . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 4. IPアドレスの書式チェック
// ---------------------------------------------------------------------
// filter_var($value, FILTER_VALIDATE_IP) を使うと、
// 自分で正規表現を書かなくても「IPv4またはIPv6として正しい形式か」を
// チェックできます。
//   - 正しい形式の場合   -> 渡した値がそのまま返る
//   - 正しくない形式の場合 -> false が返る
//
// 注意: filter_var() は失敗すると false を返しますが、
// もし将来「IPアドレスの文字列 "0"」のような紛らわしい値を扱う場合、
// false と数値の 0 や空文字列を取り違えないよう、
// 必ず === を使って「型も含めて false かどうか」を判定するのが安全です。
echo "----- 3. IPアドレスのチェック -----" . PHP_EOL;

$validatedIp = filter_var($ip, FILTER_VALIDATE_IP);

if ($validatedIp === false) {
    $errors[] = "IPアドレスの形式が正しくありません。";
    echo "NG: \"{$ip}\" は正しいIPアドレスの形式ではありません。" . PHP_EOL;
} else {
    echo "OK: \"{$validatedIp}\" は正しいIPアドレスの形式です。" . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 5. ポート番号の書式チェック(範囲チェック付き)
// ---------------------------------------------------------------------
// filter_var() の第3引数に連想配列で options を渡すと、
// 「整数であること」に加えて「一定の範囲に収まっていること」まで
// 一度にチェックできます。
// ポート番号として使える範囲は 1〜65535 なので、
// min_range(最小値)と max_range(最大値)にその値を指定します。
//
// $_POST から受け取った値は文字列("8080" など)ですが、
// FILTER_VALIDATE_INT は文字列で渡された数字も正しく整数として
// チェックしてくれます(空白を含んでいたり、数字以外の文字が
// 混ざっていたりすると失敗します)。
echo "----- 4. ポート番号のチェック -----" . PHP_EOL;

$validatedPort = filter_var($port, FILTER_VALIDATE_INT, [
    "options" => [
        "min_range" => 1,
        "max_range" => 65535,
    ],
]);

if ($validatedPort === false) {
    $errors[] = "ポート番号は1〜65535の整数で入力してください。";
    echo "NG: \"{$port}\" は1〜65535の範囲の整数ではありません。" . PHP_EOL;
} else {
    // ここまで来ると $validatedPort には int型 の値が入っています。
    echo "OK: ポート番号は {$validatedPort} (型: " . gettype($validatedPort) . ") です。" . PHP_EOL;
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 6. チェック結果をまとめて表示する
// ---------------------------------------------------------------------
// $errors が空配列のままであれば、すべてのチェックを通過したということ
// なので「登録可能です」と表示します。
// 1件でもエラーが入っていれば、その内容を一覧で表示します。
echo "----- 5. チェック結果 -----" . PHP_EOL;

if (empty($errors)) {
    echo "入力内容に問題はありません。登録可能です。" . PHP_EOL;
    // ここでもホスト名を画面に表示するので、念のため
    // htmlspecialchars() を通してから出力しています。
    // (今回のサンプルデータには危険な文字は含まれていませんが、
    //  「表示する前は必ずエスケープする」習慣を身につけることが大切です)
    echo "  ホスト名  : " . htmlspecialchars($hostname) . PHP_EOL;
    echo "  IPアドレス: " . htmlspecialchars($validatedIp) . PHP_EOL;
    echo "  ポート番号: " . htmlspecialchars((string) $validatedPort) . PHP_EOL;
} else {
    $errorCount = count($errors);
    echo "入力内容に {$errorCount} 件の問題があります。登録できません。" . PHP_EOL;
    foreach ($errors as $index => $error) {
        $number = $index + 1;
        echo "  {$number}. {$error}" . PHP_EOL;
    }
}
echo PHP_EOL;


// ---------------------------------------------------------------------
// 7. htmlspecialchars() の効果を確認する(XSS対策のデモ)
// ---------------------------------------------------------------------
// ここまでのサンプルデータには危険な文字が含まれていなかったので、
// htmlspecialchars() の効果が分かりにくかったかもしれません。
// あらためて「もし悪意のある人がホスト名の欄に不正なHTML/JavaScriptを
// 入力してきたら」という想定で、htmlspecialchars() の効果を確認します。
//
// もしこの文字列を htmlspecialchars() を通さずにそのままWebページに
// 出力してしまうと、ブラウザはそれを本物の <script> タグとして解釈し、
// ページを開いた人のブラウザ上で任意のJavaScriptが実行されてしまいます。
// これが XSS(クロスサイトスクリプティング)と呼ばれる脆弱性です。
// 例えば、他人のログイン情報(セッション情報)を盗み出すような
// スクリプトを埋め込まれると、大きな被害につながる可能性があります。
echo "----- 6. XSS対策の確認 -----" . PHP_EOL;

$maliciousHostname = "<script>alert('XSS')</script>";
$escaped = htmlspecialchars($maliciousHostname);

echo "もし悪意のある入力がホスト名として送られてきたら…" . PHP_EOL;
echo "  元の入力          : {$maliciousHostname}" . PHP_EOL;
echo "  htmlspecialchars後: {$escaped}" . PHP_EOL;
echo PHP_EOL;
echo "=> htmlspecialchars() を通すと、<script> のような文字列は" . PHP_EOL;
echo "   HTMLタグとして解釈されない、ただの \"文字\" に変換されます。" . PHP_EOL;
echo "   これにより、ブラウザがスクリプトとして実行してしまうことを防げます。" . PHP_EOL;
