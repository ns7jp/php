<?php

// =====================================================================
// 演習15: サーバー情報取得スクリプト (模範解答)
// =====================================================================
// このスクリプトは、今このPHPスクリプトが動いている環境について、
//   1. PHPのバージョン
//   2. OSの情報
//   3. ディスクの空き容量・総容量・使用率
//   4. ロードアベレージ(直近の負荷状況)
//   5. メモリ使用量
// をまとめて調べ、見やすい表形式でコンソールに表示する
// 「サーバー情報レポートツール」です。
//
// 実務のサーバー構築・運用の現場では、「今このサーバーはどういう状態か」を
// 素早く確認できるスクリプトが非常に重宝されます。今回作るツールは、
// その最初の一歩となる内容です。
// =====================================================================


// ---------------------------------------------------------------------
// 0. formatBytes() 関数(演習05で作った関数を再利用します)
// ---------------------------------------------------------------------
// バイト数(int)を "1.5 KB" のような読みやすい文字列に変換する関数です。
// ディスク容量やメモリ使用量は内部的にはすべて「バイト数」という
// 大きな整数で扱われているため、そのまま表示すると人間には読みづらくなります。
// この関数についての詳しい解説は、演習05の explanation.md を参照してください。
function formatBytes(int $bytes, int $precision = 2): string
{
    $units = ['B', 'KB', 'MB', 'GB', 'TB'];

    // 0以下の値が来た場合の安全対策(log()は0以下だと正しく計算できません)。
    if ($bytes <= 0) {
        return '0 B';
    }

    // 1024で何回割れるか(=どの単位を使うべきか)を求め、整数に切り捨てます。
    $power = (int) floor(log($bytes, 1024));
    // 配列の範囲(TBまで)を超えないようにします。
    $power = min($power, count($units) - 1);

    $value = round($bytes / (1024 ** $power), $precision);

    return $value . ' ' . $units[$power];
}


// ---------------------------------------------------------------------
// 1. PHPのバージョンを取得する
// ---------------------------------------------------------------------
// phpversion() は、今このスクリプトを実行しているPHP自体のバージョンを
// 文字列で返す、引数なしで使える組み込み関数です。
// サーバーのトラブルシューティングでは「そのサーバーのPHPが何バージョンか」を
// 確認することが第一歩になることが多く、非常によく使われます。
function getPhpVersionText(): string
{
    return phpversion();
}


// ---------------------------------------------------------------------
// 2. OSの情報を取得する
// ---------------------------------------------------------------------
// PHP_OS は「あらかじめ用意されている定数(マジック定数ではない組み込み定数)」で、
// スクリプトを動かしているOSの種類(例: "Linux", "WINNT", "Darwin" など)が
// 文字列としてあらかじめ入っています。関数ではないため、() を付けずに使います。
//
// php_uname() は、OS名だけでなく、ホスト名やカーネルのバージョンなど、
// より詳しい情報をまとめた1つの文字列として返す関数です。
// 引数を省略すると、"Linux ホスト名 カーネルバージョン ... アーキテクチャ" のような
// 詳しい情報がすべて含まれた文字列が返ってきます。
function getOsInfo(): array
{
    return [
        'os' => PHP_OS,          // 定数なので () は付けない
        'detail' => php_uname(), // 関数なので () を付けて呼び出す
    ];
}


// ---------------------------------------------------------------------
// 3. ディスクの空き容量・総容量・使用率を取得する
// ---------------------------------------------------------------------
// disk_free_space($path) は、指定したパスが存在するディスク(パーティション)の
// 「空き容量」をバイト単位(float)で返します。
// disk_total_space($path) は、同じディスクの「総容量」をバイト単位(float)で返します。
//
// どちらも環境によっては情報を取得できず false が返ってくることがあるため
// (アクセス権限がない場合や、一部の特殊な環境など)、必ず false かどうかを
// チェックしてから使うのが安全です。
function getDiskUsageRows(): array
{
    // "." は「このスクリプトを実行したときのカレントディレクトリ」を表します。
    // カレントディレクトリが存在するディスクの容量を調べる、という意味になります。
    $path = '.';

    $free = disk_free_space($path);
    $total = disk_total_space($path);

    // false が返ってきた場合や、総容量が0以下の場合は、正しく計算できないため
    // (ゼロ除算になってしまうため)、その旨をわかりやすく表示して終わります。
    if ($free === false || $total === false || $total <= 0) {
        return [
            ['ディスク容量(空き/総)', 'この環境では取得できません'],
            ['ディスク使用率', 'この環境では取得できません'],
        ];
    }

    // 使用中の容量 = 総容量 - 空き容量、という単純な引き算で求められます。
    $used = $total - $free;
    // 使用率(%) = 使用中の容量 ÷ 総容量 × 100。小数点1桁に丸めます。
    $usedPercent = round(($used / $total) * 100, 1);

    // disk_free_space() / disk_total_space() は float で返ってきますが、
    // formatBytes() は int を受け取る想定のため、(int) でキャスト(型変換)します。
    return [
        ['ディスク容量(空き/総)', formatBytes((int) $free) . ' / ' . formatBytes((int) $total)],
        ['ディスク使用率', $usedPercent . ' % 使用中(使用量: ' . formatBytes((int) $used) . ')'],
    ];
}


// ---------------------------------------------------------------------
// 4. ロードアベレージ(直近の負荷状況)を取得する
// ---------------------------------------------------------------------
// ロードアベレージとは、「直近の一定時間、CPUの処理待ちがどれくらい
// 発生していたか」を表す数値で、Linux/UnixサーバーではWebサーバーや
// データベースサーバーの負荷状況を確認する際の基本的な指標の1つです。
//
// sys_getloadavg() はこの値を [1分平均, 5分平均, 15分平均] という
// 3要素の配列(float)で返してくれる関数です。
//
// ただし、この関数は Windows 環境では利用できません(そもそも関数自体が
// 定義されていません)。存在しない関数をそのまま呼び出すと、
// "Fatal error: Uncaught Error: Call to undefined function" という
// 致命的エラーでスクリプトが止まってしまいます。
//
// そこで、function_exists("関数名") を使って「その関数が今の環境で
// 使えるかどうか」を事前に安全確認してから呼び出す、という書き方をします。
function getLoadAverageText(): string
{
    if (!function_exists('sys_getloadavg')) {
        // Windows環境など、この関数が使えない環境向けのメッセージです。
        return 'この環境では取得できません(sys_getloadavg() が利用できません)';
    }

    // [1分平均, 5分平均, 15分平均] の順で入った配列が返ってきます。
    $load = sys_getloadavg();

    // sprintf() を使い、それぞれの数値を小数点2桁に揃えて1つの文字列にまとめます。
    return sprintf(
        '%.2f, %.2f, %.2f (1分, 5分, 15分の平均)',
        $load[0],
        $load[1],
        $load[2]
    );
}


// ---------------------------------------------------------------------
// 5. メモリ使用量を取得する
// ---------------------------------------------------------------------
// memory_get_usage() は、今実行中のPHPスクリプトが使用しているメモリ量を
// バイト単位で返す関数です。
// 引数に true を渡すと、PHPの内部的な管理領域だけでなく、OSから実際に
// 確保している(割り当てられている)メモリ量全体(real usage)を返します。
// 引数を省略、または false を渡すと、PHPが実際に使用中の分だけを返します。
//
// サーバーで長時間動くバッチ処理やデーモンスクリプトを書くときは、
// この値を定期的に確認することで「メモリリーク(使用量が際限なく
// 増え続けてしまう不具合)」の兆候にいち早く気づくことができます。
function getMemoryUsageText(): string
{
    $bytes = memory_get_usage(true);

    return formatBytes($bytes) . '(memory_get_usage(true) による取得)';
}


// ---------------------------------------------------------------------
// 6.【おまけ・オプション】shell_exec() を使った安全なコマンド実行の例
// ---------------------------------------------------------------------
// shell_exec() は、OSのシェルコマンドをそのまま実行し、その出力結果を
// 文字列として受け取れる、非常に強力な関数です。
//
// ★★★ 重要:セキュリティ上の注意 ★★★
// shell_exec() に「外部からの入力(フォームの値・URLのクエリパラメータ・
// コマンドライン引数・ユーザーが入力した文字列など)」を検証せずに
// そのまま組み込んで実行してしまうと、「コマンドインジェクション」という
// 重大な脆弱性につながります。
//
// 【絶対に書いてはいけない悪い例】
//     $host = $_GET['host'];                 // 外部からの入力をそのまま受け取る
//     $result = shell_exec("ping -c 1 " . $host); // 危険!
//
//   もし $host に "example.com; rm -rf /" のような文字列を渡されると、
//   本来意図した ping コマンドだけでなく、セミコロンの後ろに続く
//   別のコマンドまで実行されてしまう可能性があります。
//   このように「外部からの入力をそのままコマンド文字列に混ぜる」ことは
//   原則として絶対に避けるべきです。どうしても使う場合は、
//   escapeshellarg() などで厳重にエスケープ(無害化)する必要があります。
//
// 【この演習で行う安全な例】
// この関数では、
//   ・外部からの入力(変数の値)を一切コマンド文字列に混ぜていない
//   ・実行するコマンドは "uptime" という、引数を持たない固定の文字列のみ
// という条件を守っているため、コマンドインジェクションの心配はありません。
// あくまで「shell_exec() 自体の使い方」を確認するための例です。
function getUptimeSafely(): ?string
{
    // shell_exec() 自体が(サーバーの設定で)無効化されている環境もあるため、
    // 念のため function_exists() で確認してから使います。
    if (!function_exists('shell_exec')) {
        return null;
    }

    // 引数を一切持たない、完全に固定された文字列だけを渡している点に注目してください。
    $output = shell_exec('uptime');

    // 実行に失敗した場合や、コマンド自体が存在しない環境では
    // null または false が返ってくることがあります。
    if ($output === null || $output === false) {
        return null;
    }

    // 実行結果の末尾に付く改行コードなどを trim() で取り除きます。
    return trim($output);
}


// =====================================================================
// メイン処理: 各関数を呼び出して結果を集め、表形式で表示する
// =====================================================================

// 表の各行を [ラベル, 値] の組み合わせとして配列にまとめていきます。
$rows = [];

$rows[] = ['PHPバージョン', getPhpVersionText()];

$osInfo = getOsInfo();
$rows[] = ['OS種別 (PHP_OS)', $osInfo['os']];
$rows[] = ['OS詳細 (php_uname())', $osInfo['detail']];

// ディスク情報は複数行になるので、foreach でまとめて追加します。
foreach (getDiskUsageRows() as $diskRow) {
    $rows[] = $diskRow;
}

$rows[] = ['ロードアベレージ', getLoadAverageText()];
$rows[] = ['メモリ使用量 (real)', getMemoryUsageText()];

// ---------------------------------------------------------------------
// 表を整えて表示する
// ---------------------------------------------------------------------
// ラベル部分(左側の項目名)の幅を揃えたいのですが、日本語(全角文字)と
// 英数字(半角文字)が混ざっていると、通常の str_pad() では表示幅の
// 計算がずれてしまいます(str_pad()は「バイト数」で長さを数えるため、
// 全角文字が想定より長く数えられてしまいます)。
//
// そこで mb_strwidth() という、mbstring拡張が提供する関数を使います。
// これは全角文字を「2」、半角文字を「1」として表示幅を計算してくれるため、
// 日本語と英数字が混在していても、見た目にきれいに揃えることができます。
$labelWidth = 0;
foreach ($rows as [$label, $value]) {
    $labelWidth = max($labelWidth, mb_strwidth($label));
}
$labelWidth += 2; // 項目名と区切り記号の間に少し余白を持たせます

$separator = str_repeat('=', 68);

echo $separator . PHP_EOL;
echo '  サーバー情報レポート  (取得時刻: ' . date('Y-m-d H:i:s') . ')' . PHP_EOL;
echo $separator . PHP_EOL;

foreach ($rows as [$label, $value]) {
    // ラベルの表示幅に合わせて、右側にスペースを埋めます。
    $pad = $labelWidth - mb_strwidth($label);
    echo $label . str_repeat(' ', $pad) . ': ' . $value . PHP_EOL;
}

echo $separator . PHP_EOL;
echo PHP_EOL;

// ---------------------------------------------------------------------
// 【おまけ】shell_exec() のデモは、明示的にオプションを付けたときだけ実行する
// ---------------------------------------------------------------------
// $argv は、コマンドラインからスクリプトを実行したときに渡された引数が
// 入っている配列です($argv[0] にはスクリプトファイル名自体が入ります)。
// ここでは "--with-uptime" というオプションが付けられていた場合だけ、
// shell_exec() を使ったデモを実行するようにしています。
echo str_repeat('-', 68) . PHP_EOL;
echo '【おまけ】shell_exec() を使った安全なコマンド実行の例' . PHP_EOL;
echo str_repeat('-', 68) . PHP_EOL;

$wantsUptimeDemo = in_array('--with-uptime', $argv, true);

if ($wantsUptimeDemo) {
    $uptime = getUptimeSafely();

    if ($uptime !== null) {
        echo 'shell_exec(\'uptime\') の実行結果:' . PHP_EOL;
        echo '  ' . $uptime . PHP_EOL;
    } else {
        echo 'この環境では uptime コマンドを実行できませんでした。' . PHP_EOL;
    }
} else {
    echo '実行時に --with-uptime オプションを付けると、' . PHP_EOL;
    echo 'shell_exec(\'uptime\') を使った安全な実行例を確認できます。' . PHP_EOL;
    echo '例: php answer.php --with-uptime' . PHP_EOL;
}

echo PHP_EOL;
echo '※ shell_exec() に外部からの入力をそのまま渡すのは大変危険です' . PHP_EOL;
echo '  (コマンドインジェクションの原因になります)。詳しくは explanation.md を参照してください。' . PHP_EOL;
