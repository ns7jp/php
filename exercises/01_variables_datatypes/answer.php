<?php
// =============================================================
// 演習01: 変数とデータ型 - 模範解答
// =============================================================
// このファイルは「答え」です。practice.php を自分で解いたあとに
// 見比べて、考え方や書き方の違いを確認するために使ってください。
//
// 実行方法: php answer.php
// =============================================================


// -------------------------------------------------------------
// 1. 各データ型の変数を宣言する
// -------------------------------------------------------------
// PHPは「動的型付け言語」なので、変数を作るときに型を書く必要は
// ありません。$記号 + 変数名 に値を代入するだけで、PHPが自動的に
// 型を判断してくれます。
//
// 変数名のルール(命名規則)
//   ・先頭は必ず $ を付ける
//   ・$の後は「英字」または「アンダースコア(_)」で始める
//   ・数字で始めることはできない( $1name はNG)
//   ・大文字・小文字は区別される($name と $Name は別の変数)
//   ・複数の単語をつなげるときは $server_name のように
//     スネークケースで書くのが一般的

$serverName   = "web-server-01"; // string(文字列)型: サーバー名を表す
$portNumber   = 8080;            // int(整数)型: ポート番号
$cpuUsage     = 12.5;            // float(浮動小数点数)型: CPU使用率(%)
$isRunning    = true;            // bool(真偽値)型: サーバーが稼働中かどうか
$serviceList  = ["nginx", "php-fpm", "mysql"]; // array(配列)型: 稼働中のサービス一覧
$lastError    = null;            // null型: エラーが「何もない」状態を表す


// -------------------------------------------------------------
// 2. gettype() で型名を確認する
// -------------------------------------------------------------
// gettype($変数) は、その変数が今どの型なのかを「文字列」として
// 返してくれる関数です。デバッグ中に「思っていた型と違う!」という
// バグを見つけるのに役立ちます。

echo "===== gettype() で型を確認する =====\n";
echo "\$serverName  の型: " . gettype($serverName) . "\n";
echo "\$portNumber  の型: " . gettype($portNumber) . "\n";
echo "\$cpuUsage    の型: " . gettype($cpuUsage) . "\n";
echo "\$isRunning   の型: " . gettype($isRunning) . "\n";
echo "\$serviceList の型: " . gettype($serviceList) . "\n";
echo "\$lastError   の型: " . gettype($lastError) . "\n";
echo "\n";


// -------------------------------------------------------------
// 3. var_dump() で型と中身を同時に確認する
// -------------------------------------------------------------
// var_dump($変数) は、型・値の長さ・中身をまとめて表示してくれる
// 関数です。特に配列の中身や、文字列と数値の見分け(例: "10" と 10 の違い)
// を確認したいときに非常に便利です。

echo "===== var_dump() で型と中身を確認する =====\n";
var_dump($serverName);
var_dump($portNumber);
var_dump($cpuUsage);
var_dump($isRunning);
var_dump($serviceList);
var_dump($lastError);
echo "\n";


// -------------------------------------------------------------
// 4. 文字列と数値を「.」(ドット演算子)で連結する
// -------------------------------------------------------------
// PHPでは文字列同士、または文字列と数値をつなげるときに
// 「.」(ドット)を使います。他の言語で使う「+」ではないので注意。
// 数値を文字列に連結すると、PHPが自動的に文字列に変換してくれます
// (これを「暗黙の型変換」と呼びます)。

echo "===== ドット演算子(.)による文字列連結 =====\n";
$message = "サーバー「" . $serverName . "」はポート " . $portNumber . " で待受中です。";
echo $message . "\n";

// 数値同士を . でつなぐと「文字列として連結」されるので注意。
// 例えば 1 . 2 は 1+2=3 ではなく、文字列 "12" になります。
$concatNumbers = 1 . 2;
echo "1 . 2 の結果: " . $concatNumbers . "(型: " . gettype($concatNumbers) . ")\n";
echo "\n";


// -------------------------------------------------------------
// 5. 型変換(キャスト)を行う
// -------------------------------------------------------------
// 「キャスト」とは、変数の型を別の型に強制的に変換することです。
// 変換したい型を丸カッコで囲んで、変数の前に書きます。
// 例: (int)$変数  (string)$変数  (float)$変数  (bool)$変数

echo "===== (int) / (string) によるキャスト =====\n";

// 文字列 "8080" を数値として扱いたい場合、(int) でキャストする
$portAsString = "8080";
$portAsInt = (int) $portAsString;
echo "文字列 \"$portAsString\" を (int) でキャスト -> " . $portAsInt
    . "(型: " . gettype($portAsInt) . ")\n";

// 数値 12.5 を文字列として扱いたい場合、(string) でキャストする
$cpuAsString = (string) $cpuUsage;
echo "数値 $cpuUsage を (string) でキャスト -> \"" . $cpuAsString
    . "\"(型: " . gettype($cpuAsString) . ")\n";

// 小数を (int) でキャストすると、小数点以下が切り捨てられる点に注意
$floatValue = 9.99;
$intFromFloat = (int) $floatValue;
echo "$floatValue を (int) でキャスト -> " . $intFromFloat . "(小数点以下は切り捨て)\n";
echo "\n";


// -------------------------------------------------------------
// 6. intval() / strval() を使った変換
// -------------------------------------------------------------
// (int) や (string) と同じような役割を持つ「関数」として、
// intval() と strval() があります。設定ファイルから読み込んだ値など、
// 「文字列だけど数値として扱いたい」場面でよく使われます。

echo "===== intval() / strval() による変換 =====\n";

// 設定ファイルからポート番号を読み込んだ想定(実際にはすべて文字列になる)
$timeoutFromConfig = "30";        // 例: タイムアウト秒数(文字列)
$timeoutSeconds = intval($timeoutFromConfig); // 文字列 -> 整数へ変換
echo "設定値 \"$timeoutFromConfig\" を intval() で変換 -> " . $timeoutSeconds
    . "(型: " . gettype($timeoutSeconds) . ")\n";

// 逆に、数値を文字列として画面やログに出力したい場合は strval() を使う
$retryCount = 3;
$retryCountText = strval($retryCount);
echo "数値 " . $retryCount . " を strval() で変換 -> \"" . $retryCountText
    . "\"(型: " . gettype($retryCountText) . ")\n";

// intval() は先頭が数字の文字列なら、途中までを読み取って変換もできる
$mixedText = "80px"; // 例: "80px" のような単位付き文字列
echo "\"$mixedText\" を intval() で変換 -> " . intval($mixedText)
    . "(数字以外の部分は無視される)\n";
echo "\n";


// -------------------------------------------------------------
// 7. 定数(define / const)を使う
// -------------------------------------------------------------
// 「定数」は、一度値を決めたらプログラムの実行中に変更できない値です。
// サーバー名やAPIキーなど、「途中で書き換わってほしくない値」を
// 定数として定義しておくと、意図しない上書きを防げます。
//
// 定義方法は2種類あります。
//   1) define('定数名', 値);   -> 関数の中などでも実行時に定義できる
//   2) const 定数名 = 値;      -> クラスの外側では基本的にファイルの
//                                 トップレベルに書く。実行前に定義される

define('SERVER_NAME', 'web-server-01.example.com');
const MAX_CONNECTIONS = 100;

echo "===== 定数(define / const) =====\n";
echo "SERVER_NAME の値: " . SERVER_NAME . "\n";
echo "MAX_CONNECTIONS の値: " . MAX_CONNECTIONS . "\n";

// 定数名の前には $ を付けない点が、変数との大きな違いです。
// また、defined() 関数を使うと「その定数が既に定義済みかどうか」を
// チェックすることもできます。
if (defined('SERVER_NAME')) {
    echo "SERVER_NAME はすでに定義されています。\n";
}

echo "\n";
echo "===== すべての処理が完了しました =====\n";
